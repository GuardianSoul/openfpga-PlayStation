-- CPU-assisted save states (scripts/prepare_save_states.py): the MiSTer CPU
-- and memorymux with the trap and EXP1 transforms, an SDRAM model (from
-- tb_memorymux_fifo_cpu.vhd), and an EXP1 device model with the register map
-- of rtl/pocket/psx_save_exp1.sv: the handler ROM (rom_exp1.hex), a staging
-- page, page copies to and from a save buffer, STATUS/ACK/FINISH and the trap.
-- A generated game program (ram.hex, started by rom.hex) runs with IEc=1.
-- SAVE_AT / LOAD_AT (clk1x cycles, 0 = never) raise a save or load request.
-- A GPU model (GPUSTAT fields, GP0 E1-E6 / A0 / C0 / 1F, GP1 00-08 / 10h,
-- VRAM_ROWS rows of 1024 pixels, reads stalled 0-3 cycles) gives the handler's
-- quiet-point check, GPU settings and VRAM copies something to work on.
-- An SPU model (in the EXP1 process: the SPU bus and SPU RAM) changes SPU
-- RAM and a hidden "voice in ADSR release" mask with every guest register
-- write, holds like the tapped SPU (quiet some cycles after SPU_HOLD; held,
-- 0x1F801DBC/E read the mask), and takes key on/off writes like the SPU
-- (consumed, they read back 0). Its ADSR volumes (voice register 0x0C) are
-- the engine's, so they are not compared; instead, when a load releases the
-- SPU, the model checks the handler's re-key against the state at the save:
-- voices with volume not releasing keyed on, the others volume 0 and keyed off.
-- At the finish marker the bench writes RAM 0..DUMP_BYTES-1, the GPU state,
-- VRAM and the SPU state to dump.hex; the runner compares dumps between runs. Declarations, instances and stubs are
-- generated by scripts/run_save_trap_cpu.py.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;
use std.textio.all;
use std.env.all;
use work.pexport.all;

entity tb_save_trap_cpu is
   generic
   (
      SEED       : positive := 1;
      SAVE_AT    : natural  := 0;
      LOAD_AT    : natural  := 0;
      LOAD_DELAY : natural  := 0;     -- else: the load this many cycles after the first save has finished
      BUF_PAGES  : positive := 24;    -- buffer pages kept; page 2047 maps to the last one
      DUMP_BYTES : positive := 16384;
      MAX_CYCLES : natural  := 3000000;
      PROGRESS   : natural  := 0;
      VRAM_ROWS  : positive := 5;
      SPU_PAGES  : positive := 2;     -- SPU RAM pages of 1024 halfwords (ROM word 0xFF4)
      DMA_HOLD   : natural  := 0;     -- channels 0, 1 and 3 report busy this long from SAVE_AT, with CPU stalls in bursts
      GPU_HOLD   : natural  := 0;     -- the GPU reports a command in progress for this long from SAVE_AT (to the routine)
      VRAM_SEND  : boolean  := false; -- GPUSTAT 27 reads 1 while the routine runs (VRAM data the game never reads)
      CD_UNREAD  : boolean  := false; -- at SAVE_AT the game leaves a response byte unread (flag acked)
      CD_LEFT    : natural  := 0;     -- at SAVE_AT the data FIFO holds this many bytes the game has not read
      STAGE2_WARM : boolean := false; -- stage 2 already unpacked at STAGE2 (stage2.hex), as after an earlier trap
      PAD_SELECT : natural  := 0;     -- JOY_CTRL shows a device selected this long from SAVE_AT (to the routine)
      LOAD_DISC  : natural  := 0;     -- the disc in the drive (0x180B) during a load; 0 while saving
      CD_FRESH   : boolean  := false; -- a load finds the drive fresh (a wake from Sleep): motor off, idle
      CD_STRAY   : boolean  := false; -- a load finds the BIOS's last command unanswered (a wake from Sleep):
                                      -- its INT3 not acked and its INT2 queued behind it (cd_top pendingDriveIRQ)
      ZERO_ROW   : natural  := 4      -- this VRAM row starts all zero (a packed save leaves it out)
   );
end entity;

architecture test of tb_save_trap_cpu is
   type words is array(natural range <>) of std_logic_vector(31 downto 0);
   impure function load(path : string; size : positive; sparse : boolean) return words is
      file data : text open read_mode is path;
      variable row : line;
      variable result : words(0 to size - 1) := (others => (others => '0'));
      variable address : std_logic_vector(31 downto 0);
      variable index : natural := 0;
   begin
      while not endfile(data) loop
         readline(data, row);
         if sparse then hread(row, address); index := to_integer(unsigned(address)) / 4; end if;
         assert index < size report "image exceeds memory" severity failure;
         hread(row, result(index)); index := index + 1;
      end loop;
      return result;
   end function;
   constant rom : words(0 to 127) := load("rom.hex", 128, false);
   constant exp1_rom : words(0 to 2047) := load("rom_exp1.hex", 2048, false);

   signal clk1x, clk2x, clk3x : std_logic := '1';
   signal reset, ss_reset : std_logic := '1';
   signal ce : std_logic := '1';
   signal cpuPaused, pause_next : std_logic := '0';
   signal dma_bursts : natural := 0;
   signal ram_data : std_logic_vector(31 downto 0) := (others => '0');
   signal ram_cpu_done : std_logic := '0';
   signal cache_wr : std_logic_vector(3 downto 0) := "0000";
   signal cache_data : std_logic_vector(31 downto 0) := (others => '0');
   signal cache_addr : std_logic_vector(7 downto 0) := (others => '0');
   signal lfsr : unsigned(63 downto 0) := x"0123456789ABCDEF";
   signal finished : std_logic := '0';

   -- EXP1 device model
   signal trap, want_save, want_load, cp_busy : std_logic := '0';
   signal in_handler : std_logic := '0';   -- from the routine's ACK to its FINISH (GPU_HOLD / VRAM_SEND apply then)
   signal exp1_q : std_logic_vector(7 downto 0) := (others => '0');
   signal finish_code : natural := 0;
   signal saves_done, saves_failed, loads_done, loads_failed, handler_fetches, retries : natural := 0;

   -- GPU model
   signal gpu_vram : words(0 to VRAM_ROWS * 512 - 1);
   signal gpu_stat_s : std_logic_vector(31 downto 0) := (others => '0');
   signal gpu_tw, gpu_e3, gpu_e4, gpu_e5 : std_logic_vector(31 downto 0) := (others => '0');
   signal gpu_ranges : std_logic_vector(62 downto 0) := (others => '0');
   signal gpu_q : std_logic_vector(31 downto 0) := (others => '0');
   signal gpu_stall : std_logic := '0';

   -- SPU model
   type halves is array(natural range <>) of std_logic_vector(15 downto 0);
   signal spu_hold, spu_quiet : std_logic := '0';
   signal spu_q : std_logic_vector(15 downto 0) := (others => '0');
   signal spu_regs_s : halves(0 to 255);
   signal spu_ram_s : halves(0 to SPU_PAGES * 1024 - 1);
   signal spu_guest_writes, spu_rekeys : natural := 0;

   -- CD controller model
   signal cd_state_s : std_logic_vector(63 downto 0) := (others => '0');
   signal cd_q : std_logic_vector(7 downto 0) := (others => '0');
   signal cd_capt : natural := 0;          -- the LBA a save read from 0x181C-0x181E
   signal cd_put_tgl : std_logic := '0';   -- CD_PUT (0x180D): a byte into the data FIFO
   signal save_mode_s : std_logic := '0';  -- SAVE_MODE (0x180E): the CPU reaches stage 2's SDRAM
   signal cd_freeze_s : std_logic := '0';  -- CD_FREEZE (0x180F): the CD model stands still
   signal cd_put_byte : std_logic_vector(7 downto 0) := (others => '0');
   signal cd_saves_quiet : natural := 0;

   signal cycle_count, retired, log_stores : natural := 0;
   signal clk1xToggle, clk1xToggle2x, clk2xIndex, gte_busy : std_logic := '0';
   signal gte_readData : unsigned(31 downto 0);

   -- GENERATED_DECLARATIONS
begin

   clk1x <= not clk1x after 15 ns;
   clk2x <= not clk2x after 7500 ps;
   clk3x <= not clk3x after 5 ns;

   pause_next <= cpuPaused;

   -- DMA model: MDEC in/out and CD channels busy in CHCR, and the CPU paused as
   -- psx_top does for DMA (cpuPaused; a burst starts only when memorymux is idle). No RAM traffic.
   dma_model : process(clk1x)
      variable left, gap : natural := 0;
   begin
      if rising_edge(clk1x) then
         bus_dma_dataRead <= (others => '0');
         if DMA_HOLD > 0 and cycle_count >= SAVE_AT and cycle_count < SAVE_AT + DMA_HOLD then
            if mux_bus_dma_read = '1' and (mux_bus_dma_addr = 8 or mux_bus_dma_addr = 24 or mux_bus_dma_addr = 56) then
               bus_dma_dataRead <= x"01000000";
            end if;
            if left > 0 then
               left := left - 1;
               if left = 0 then cpuPaused <= '0'; gap := 1500; end if;
            elsif gap > 0 then
               gap := gap - 1;
            elsif mux_isIdle = '1' then
               cpuPaused <= '1'; left := 400; dma_bursts <= dma_bursts + 1;
            end if;
         else
            cpuPaused <= '0'; left := 0; gap := 0;
         end if;
      end if;
   end process;

   -- pad / memory card port: JOY_CTRL (0x1F80104A) with /JOY select on in the PAD_SELECT window
   -- (while the routine runs: the game runs as in the reference); everything else reads 0
   pad_model : process(clk1x)
   begin
      if rising_edge(clk1x) then
         bus_pad_dataRead <= (others => '0');
         if PAD_SELECT > 0 and in_handler = '1' and cycle_count >= SAVE_AT and cycle_count < SAVE_AT + PAD_SELECT then
            bus_pad_dataRead <= x"00020002";
         end if;
      end if;
   end process;

   -- psx_top's clk2xIndex (the GTE's clk2x phase)
   process (clk1x) begin if rising_edge(clk1x) then clk1xToggle <= not clk1xToggle; end if; end process;
   process (clk2x)
   begin
      if rising_edge(clk2x) then
         clk1xToggle2x <= clk1xToggle;
         clk2xIndex <= '0';
         if clk1xToggle2x = clk1xToggle then clk2xIndex <= '1'; end if;
      end if;
   end process;

   -- GENERATED_INSTANCES

   process
   begin
      for edge in 1 to 4 loop wait until falling_edge(clk1x); end loop;
      ss_reset <= '0';
      for edge in 1 to 50 loop wait until falling_edge(clk1x); end loop;
      reset <= '0';
      wait;
   end process;

   process (clk1x)
   begin
      if rising_edge(clk1x) then
         cycle_count <= cycle_count + 1;
         assert cycle_count < MAX_CYCLES report "program did not finish" severity failure;
         lfsr <= lfsr(62 downto 0) & (lfsr(63) xor lfsr(62) xor lfsr(60) xor lfsr(59));
         -- GENERATED_STUBS
         if PROGRESS > 0 and cycle_count mod PROGRESS = 0 then
            report "progress cycles=" & integer'image(cycle_count) & " retired=" & integer'image(retired) &
               " log_stores=" & integer'image(log_stores) & " pc=" & to_hstring(cpu_cpu_export.pc);
         end if;
         if reset = '0' and ce = '1' and cpu_cpu_done = '1' then
            retired <= retired + 1;
            assert cpu_cpu_export.pc /= x"80000080" and cpu_cpu_export.pc /= x"BFC00180"
               report "program took a normal exception: cause=" & to_hstring(cpu_cpu_export.cause) &
                  " epc(r) k0=" & to_hstring(cpu_cpu_export.regs(26)) & " ra=" & to_hstring(cpu_cpu_export.regs(31))
               severity failure;
         end if;
         if reset = '0' and ce = '1' and cpu_cpu_done = '1' and cpu_cpu_export.pc(31 downto 13) = x"BF00" & "000" then
            assert std_logic_vector(cpu_cpu_export.opcode) = exp1_rom(to_integer(cpu_cpu_export.pc(12 downto 2)))
               report "handler opcode at " & to_hstring(cpu_cpu_export.pc) & " is " & to_hstring(cpu_cpu_export.opcode) &
                  ", ROM has " & to_hstring(exp1_rom(to_integer(cpu_cpu_export.pc(12 downto 2)))) severity failure;
            assert cpu_cpu_export.pc(12 downto 0) < 16#1000# or cpu_cpu_export.pc(12 downto 0) >= 16#1C00#
               report "handler runs outside its ROMs at " & to_hstring(cpu_cpu_export.pc) severity failure;
         end if;
         if reset = '0' and cpu_mem_request = '1' and cpu_mem_isData = '0' and
            cpu_mem_addressInstr(31 downto 12) = x"BF000" then
            handler_fetches <= handler_fetches + 1;
         end if;
      end if;
   end process;

   -- ---------------- EXP1 device model ----------------
   -- Read data is registered on clk2x from the bus address (the device's
   -- M10K timing); writes are taken on clk1x when bus_exp1_write is high.
   process (clk2x)
      variable page : words(0 to 511) := (others => (others => '0'));
      variable buf : words(0 to BUF_PAGES * 512 - 1) := (others => x"DEADBEEF");
      variable a : natural;
      variable w : std_logic_vector(31 downto 0);
      variable page_lo, page_hi : natural := 0;
      variable p, busy_left, retry_left : natural := 0;
      variable at_cpu_edge : boolean;
      variable regs : halves(0 to 255) := (others => (others => '0'));
      variable rel, snap_rel, kon_w, koff_w, keyon : std_logic_vector(31 downto 0) := (others => '0');
      variable snap_vol : halves(0 to 23) := (others => (others => '0'));
      variable kon_seen : boolean := false;
      variable spuram : halves(0 to SPU_PAGES * 1024 - 1) := (others => (others => '0'));
      variable quiet_left, sa : natural := 0;
      variable sd : std_logic_vector(15 downto 0);
      variable size_pages, stored : natural := 0;
      variable tap7 : boolean := false;
      variable load_at_v : natural := LOAD_AT;
      variable load_armed : boolean := LOAD_DELAY > 0;
      -- registers a load does not write back (ENDX, FIFO data, SPUSTAT, current main volume)
      function spu_skipped(a : natural) return boolean is
      begin
         return a = 16#19C# or a = 16#19E# or a = 16#1A8# or a = 16#1AE# or a = 16#1B8# or a = 16#1BA#;
      end function;
      -- registers the model does not store: key on/off (consumed) and the release mask
      function spu_unstored(a : natural) return boolean is
      begin
         return (a >= 16#188# and a < 16#190#) or a = 16#1BC# or a = 16#1BE#;
      end function;
      impure function slot(n : natural) return natural is
      begin
         if n >= 2045 then return BUF_PAGES - 2048 + n; end if;   -- scratch pages 2045-2047 at the end
         assert n < BUF_PAGES - 3 report "save page " & integer'image(n) & " outside the model buffer" severity failure;
         return n;
      end function;
   begin
      if rising_edge(clk2x) then
         at_cpu_edge := clk1x = '1' and clk1x'last_event = 0 ns;
         a := to_integer(mux_bus_exp1_addr);
         if a < 16#1000# or a >= 16#1C00# then
            w := exp1_rom(a / 4);
            exp1_q <= w(8 * (a mod 4) + 7 downto 8 * (a mod 4));
         elsif a >= 16#1818# and a < 16#1820# then
            exp1_q <= cd_state_s(8 * (a - 16#1818#) + 7 downto 8 * (a - 16#1818#));
            -- (on a read: the address bus also shows other devices' low address bits)
            if a = 16#181C# and want_save = '1' and mux_bus_exp1_read = '1' then cd_capt <= to_integer(unsigned(cd_state_s(55 downto 32))); end if;
         elsif a < 16#1800# then
            w := page((a - 16#1000#) / 4);
            exp1_q <= w(8 * (a mod 4) + 7 downto 8 * (a mod 4));
         elsif a = 16#1800# then
            exp1_q <= "00000" & want_load & want_save & cp_busy;
         elsif a >= 16#1810# and a < 16#1818# then
            w := gpu_ranges(31 downto 0);
            if a >= 16#1814# then w := '0' & gpu_ranges(62 downto 32); end if;
            exp1_q <= w(8 * (a mod 4) + 7 downto 8 * (a mod 4));
         elsif a = 16#180B# then
            if want_load = '1' then exp1_q <= std_logic_vector(to_unsigned(LOAD_DISC, 8)); else exp1_q <= x"00"; end if;
         elsif a = 16#180C# then
            exp1_q <= "0000000" & spu_quiet;
         else
            exp1_q <= x"00";
         end if;
         if retry_left > 0 and at_cpu_edge then
            retry_left := retry_left - 1;
            if retry_left = 0 then trap <= '1'; end if;
         end if;
         if busy_left > 0 then
            busy_left := busy_left - 1;
            if busy_left = 0 then cp_busy <= '0'; end if;
         end if;
         -- SPU model: quiet a while after the hold
         if spu_hold = '0' then spu_quiet <= '0'; quiet_left := 100 + to_integer(lfsr(10 downto 0));
         elsif quiet_left > 0 then quiet_left := quiet_left - 1;
         else spu_quiet <= '1'; end if;
         if at_cpu_edge and ce = '1' and mux_bus_spu_read = '1' then
            sa := to_integer(mux_bus_spu_addr);
            spu_q <= (others => '0');
            if sa < 16#200# and not spu_skipped(sa) and not spu_unstored(sa) then spu_q <= regs(sa / 2); end if;
            -- the release mask, only while held (all ones otherwise, like the tapped SPU)
            if sa = 16#1BC# or sa = 16#1BE# then
               spu_q <= x"FFFF";
               if spu_hold = '1' and sa = 16#1BC# then spu_q <= rel(15 downto 0); end if;
               if spu_hold = '1' and sa = 16#1BE# then spu_q <= rel(31 downto 16); end if;
            end if;
            -- a save reads the mask while held: the state the re-key check uses
            if spu_hold = '1' and sa = 16#1BE# then
               snap_rel := rel;
               for v in 0 to 23 loop snap_vol(v) := regs(8 * v + 6); end loop;
            end if;
         end if;
         if at_cpu_edge and ce = '1' and mux_bus_spu_write = '1' then
            sa := to_integer(mux_bus_spu_addr); sd := mux_bus_spu_dataWrite;
            if spu_hold = '0' then
               -- a guest write: the register, one release mask bit and one SPU RAM halfword
               if sa < 16#200# and not spu_skipped(sa) and not spu_unstored(sa) then regs(sa / 2) := sd; end if;
               rel((sa / 2 * 7 + to_integer(unsigned(sd))) mod 24) := not rel((sa / 2 * 7 + to_integer(unsigned(sd))) mod 24);
               spuram((to_integer(unsigned(sd)) * 7 + sa) mod (SPU_PAGES * 1024)) := sd xor std_logic_vector(to_unsigned(sa, 16));
               spu_guest_writes <= spu_guest_writes + 1;
            else
               assert sa < 16#200# report "handler wrote SPU register " & to_hstring(to_unsigned(sa, 12)) severity failure;
               assert spu_quiet = '1' report "SPU register write before the quiet point" severity failure;
               assert not spu_skipped(sa) report "handler wrote SPU register " & to_hstring(to_unsigned(sa, 12)) severity failure;
               if not spu_skipped(sa) and not spu_unstored(sa) then regs(sa / 2) := sd; end if;
               -- key on/off while held: the SPU takes them when released
               if sa = 16#188# then kon_w(15 downto 0) := sd; kon_seen := true; end if;
               if sa = 16#18A# then kon_w(31 downto 16) := sd; kon_seen := true; end if;
               if sa = 16#18C# then koff_w(15 downto 0) := sd; kon_seen := true; end if;
               if sa = 16#18E# then koff_w(31 downto 16) := sd; kon_seen := true; end if;
            end if;
         end if;
         -- SAVE_MODE as psx_save_exp1 takes it: on the first clk2x edge with the write strobe high
         -- (wr_edge), half a clk1x cycle after memorymux raises it, so the level is in place at the
         -- next clk1x edge (the edge memorymux can register the following access on)
         if mux_bus_exp1_write = '1' and a = 16#180E# then save_mode_s <= mux_bus_exp1_dataWrite(0); end if;
         if at_cpu_edge and ce = '1' and mux_bus_exp1_write = '1' then
            -- the set tap: CD_PUT pushes one byte per tap; any other register write ends it
            if a = 16#180F# then cd_freeze_s <= mux_bus_exp1_dataWrite(0); end if;
            if a >= 16#1800# and a < 16#1810# then
               if a = 16#180D# then
                  if not tap7 then cd_put_tgl <= not cd_put_tgl; cd_put_byte <= mux_bus_exp1_dataWrite; end if;
                  tap7 := true;
               else
                  tap7 := false;
               end if;
            end if;
            if a >= 16#1000# and a < 16#1800# then
               page((a - 16#1000#) / 4)(8 * (a mod 4) + 7 downto 8 * (a mod 4)) := mux_bus_exp1_dataWrite;
            elsif a = 16#1800# and mux_bus_exp1_dataWrite(2) = '1' then
               assert cp_busy = '0' report "COMMAND while a copy runs" severity failure;
               assert spu_hold = '1' and spu_quiet = '1' report "SPU RAM copy while the SPU runs" severity failure;
               assert page_lo < SPU_PAGES report "SPU RAM page outside the model" severity failure;
               for k in 0 to 511 loop
                  if mux_bus_exp1_dataWrite(1) = '1' then
                     page(k) := spuram(page_lo * 1024 + 2 * k + 1) & spuram(page_lo * 1024 + 2 * k);
                  else
                     spuram(page_lo * 1024 + 2 * k) := page(k)(15 downto 0);
                     spuram(page_lo * 1024 + 2 * k + 1) := page(k)(31 downto 16);
                  end if;
               end loop;
               cp_busy <= '1'; busy_left := 200 + to_integer(lfsr(7 downto 0));
            elsif a = 16#1800# then
               assert cp_busy = '0' report "COMMAND while a copy runs" severity failure;
               if mux_bus_exp1_dataWrite(0) = '1' then
                  p := slot(page_hi * 256 + page_lo);
                  if mux_bus_exp1_dataWrite(1) = '0' and want_save = '1' and page_hi * 256 + page_lo < 2045 and
                     page_hi * 256 + page_lo + 1 > stored then   -- (2045-2047: scratch pages, not the state)
                     stored := page_hi * 256 + page_lo + 1;
                  end if;
                  for k in 0 to 511 loop
                     if mux_bus_exp1_dataWrite(1) = '1' then page(k) := buf(p * 512 + k);
                     else buf(p * 512 + k) := page(k); end if;
                  end loop;
                  cp_busy <= '1'; busy_left := 20 + to_integer(lfsr(5 downto 0));
               end if;
            elsif a = 16#1801# then
               page_lo := to_integer(unsigned(mux_bus_exp1_dataWrite));
            elsif a = 16#1802# then
               page_hi := to_integer(unsigned(mux_bus_exp1_dataWrite(2 downto 0)));
            elsif a = 16#1803# and mux_bus_exp1_dataWrite(2) = '1' then
               trap <= '0'; retry_left := 3000; retries <= retries + 1; in_handler <= '0';
            elsif a = 16#1818# then
               size_pages := size_pages - size_pages mod 256 + to_integer(unsigned(mux_bus_exp1_dataWrite));
            elsif a = 16#1819# then
               size_pages := size_pages mod 256 + 256 * to_integer(unsigned(mux_bus_exp1_dataWrite(3 downto 0)));
            elsif a = 16#1803# then
               if want_save = '1' and mux_bus_exp1_dataWrite(0) = '1' then
                  assert size_pages = stored report "save size " & integer'image(size_pages) & " pages, stored " &
                     integer'image(stored) severity failure;
                  report "packed save: " & integer'image(stored) & " pages" severity note;
               end if;
               stored := 0;
               if want_save = '1' then
                  if mux_bus_exp1_dataWrite(0) = '1' then saves_done <= saves_done + 1;
                  else saves_failed <= saves_failed + 1; end if;
               elsif want_load = '1' then
                  if mux_bus_exp1_dataWrite(0) = '1' then loads_done <= loads_done + 1;
                  else loads_failed <= loads_failed + 1; end if;
               end if;
               want_save <= '0'; want_load <= '0'; in_handler <= '0';
               finish_code <= to_integer(unsigned(mux_bus_exp1_dataWrite));
               if want_save = '1' then
                  report "save taken at EPC " & to_hstring(buf(36)) severity note;
               end if;
            elsif a = 16#1804# then
               trap <= '0'; in_handler <= '1';
            elsif a = 16#180C# then
               spu_hold <= mux_bus_exp1_dataWrite(0);
               -- a load releases the SPU: check the re-key against the save
               if mux_bus_exp1_dataWrite(0) = '0' and kon_seen then
                  keyon := (others => '0');
                  for v in 0 to 23 loop
                     if snap_vol(v) /= x"0000" and snap_rel(v) = '0' then keyon(v) := '1'; end if;
                     if keyon(v) = '1' then
                        assert regs(8 * v + 6) = snap_vol(v) report "SPU voice " & integer'image(v) & " ADSR volume not restored" severity failure;
                     else
                        assert regs(8 * v + 6) = x"0000" report "SPU voice " & integer'image(v) & " not silenced on load" severity failure;
                     end if;
                  end loop;
                  assert kon_w(23 downto 0) = keyon(23 downto 0) report "SPU key on " & to_hstring(kon_w) & ", expected " & to_hstring(keyon) severity failure;
                  assert koff_w(23 downto 0) = not keyon(23 downto 0) report "SPU key off " & to_hstring(koff_w) & ", expected " & to_hstring(not keyon) severity failure;
                  spu_rekeys <= spu_rekeys + 1;
                  kon_seen := false;
               end if;
            elsif a >= 16#180D# and a <= 16#180F# then
               null;   -- CD_PUT, SAVE_MODE, CD_FREEZE (handled above)
            end if;
         end if;
         spu_regs_s <= regs; spu_ram_s <= spuram;
         for v in 0 to 23 loop spu_regs_s(8 * v + 6) <= x"0000"; end loop;   -- ADSR volumes: the engine's
         if at_cpu_edge then
            if SAVE_AT > 0 and cycle_count = SAVE_AT then
               assert want_save = '0' and want_load = '0' report "save request while busy" severity failure;
               want_save <= '1'; trap <= '1';
            end if;
            if load_armed and saves_done > 0 and want_save = '0' then
               load_at_v := cycle_count + LOAD_DELAY; load_armed := false;
            end if;
            if load_at_v > 0 and cycle_count = load_at_v then
               assert want_save = '0' and want_load = '0' report "load request while busy" severity failure;
               want_load <= '1'; trap <= '1';
            end if;
         end if;
      end if;
   end process;
   bus_exp1_dataRead <= exp1_q;
   bus_spu_dataRead <= spu_q;

   -- ---------------- CD controller model ----------------
   -- The game (set up by the generics) has the drive reading from LBA 1000
   -- in mode 0x80 with an XA filter; every 4,000 cycles a sector is read
   -- (busy for 300 cycles, as a drive interrupt on its way). The game never
   -- writes the CD registers, so any command during a save is the handler's
   -- fault. A load must pause the drive and restart it: mode, filter, demute,
   -- Setloc to the sector after the one the save read (0x181C), ReadN, then
   -- IRQENA and the index as the game had them.
   bus_cd_dataRead <= cd_q;
   process (clk1x)
      type fifo is array(0 to 15) of std_logic_vector(7 downto 0);
      constant GAME_MODE : std_logic_vector(7 downto 0) := x"C8";
      constant GAME_FILE : std_logic_vector(7 downto 0) := x"01";
      constant GAME_CHAN : std_logic_vector(7 downto 0) := x"05";
      variable idx : natural range 0 to 3 := 1;
      variable irqena : std_logic_vector(4 downto 0) := "11111";
      variable flag : std_logic_vector(4 downto 0) := "00000";
      variable resp, par : fifo;
      variable resp_n, resp_rd, par_n : natural := 0;
      variable mode : std_logic_vector(7 downto 0) := GAME_MODE;
      variable xfile : std_logic_vector(7 downto 0) := GAME_FILE;
      variable xchan : std_logic_vector(7 downto 0) := GAME_CHAN;
      variable motor, reading, playing, demuted : boolean := true;
      variable lba, target : natural := 1000;
      variable cmd : std_logic_vector(7 downto 0);
      variable cmd_left, int2_left, sector_left, busy_left, motor_left : natural := 0;
      variable sector_left_init : boolean := false;
      variable loading, was_load : boolean := false;
      variable setloc_seen, readn_seen : boolean := false;
      variable stray2 : boolean := false;   -- CD_STRAY: the queued INT2, which a new command does not cancel
      variable a : natural;
      variable d : std_logic_vector(7 downto 0);
      variable last_loads : natural := 0;
      variable ncmd, ncmd_seen : natural := 0;   -- CD commands written; at the last checked load
      variable busy : std_logic;
      type bytes is array(0 to 4095) of std_logic_vector(7 downto 0);
      variable dfifo : bytes;
      variable dn, dh : natural := 0;
      variable put_seen : std_logic := '0';
      variable last_saves : natural := 0;
      variable save_lba : natural := 0;
      function left_byte(k : natural) return std_logic_vector is
      begin
         return std_logic_vector(to_unsigned((k * 37 + k / 256 * 11 + 5) mod 256, 8));
      end function;
      procedure dpush(v : std_logic_vector(7 downto 0)) is
      begin
         assert dn < 4096 report "CD data FIFO overflow" severity failure;
         dfifo((dh + dn) mod 4096) := v; dn := dn + 1;
      end procedure;
      impure function left_ok return boolean is
      begin
         if dn /= CD_LEFT then return false; end if;
         for k in 0 to CD_LEFT - 1 loop
            if dfifo((dh + k) mod 4096) /= left_byte(k) then return false; end if;
         end loop;
         return true;
      end function;
      impure function stat return std_logic_vector is
         variable s : std_logic_vector(7 downto 0) := x"00";
      begin
         if motor then s(1) := '1'; end if;
         if reading then s(5) := '1'; end if;
         if playing then s(7) := '1'; end if;
         return s;
      end function;
      procedure push(v : std_logic_vector(7 downto 0)) is
      begin
         resp((resp_rd + resp_n) mod 16) := v; resp_n := resp_n + 1;
      end procedure;
      function bcd(v : std_logic_vector(7 downto 0)) return natural is
      begin
         return to_integer(unsigned(v(7 downto 4))) * 10 + to_integer(unsigned(v(3 downto 0)));
      end function;
   begin
      if rising_edge(clk1x) and cd_freeze_s = '1' then
         assert not (ce = '1' and (mux_bus_cd_read = '1' or mux_bus_cd_write = '1'))
            report "CD register access while the CD is frozen" severity failure;
      elsif rising_edge(clk1x) then
         if not sector_left_init then sector_left := 4000; sector_left_init := true; end if;
         -- a fresh drive at the load (a wake from Sleep)
         if CD_FRESH and want_load = '1' and not loading then
            motor := false; reading := false; playing := false; mode := x"00"; xfile := x"00"; xchan := x"00";
            irqena := "00000"; idx := 0; flag := "00000"; resp_n := 0; par_n := 0; cmd_left := 0; int2_left := 0;
            motor_left := 30000;
         end if;
         if CD_UNREAD and SAVE_AT > 0 and cycle_count = SAVE_AT then push(stat); end if;
         -- the game leaves the rest of a sector in the data FIFO
         if CD_LEFT > 0 and SAVE_AT > 0 and cycle_count = SAVE_AT then
            dn := 0; dh := 0;
            for k in 0 to CD_LEFT - 1 loop dpush(left_byte(k)); end loop;
         end if;
         if cd_put_tgl /= put_seen then put_seen := cd_put_tgl; dpush(cd_put_byte); end if;
         -- a finished save: the game finds its data FIFO as it left it; then it reads on (other bytes)
         if saves_done /= last_saves then
            last_saves := saves_done;
            -- the drive stood still from the save's quiet point (a sector or so for the FIFO bytes)
            assert CD_LEFT > 0 or lba <= cd_capt + 1
               report "save: the drive read on to " & integer'image(lba) & " from " & integer'image(cd_capt) severity failure;
            assert left_ok report "save: the CD data FIFO is not as the game left it (" & integer'image(dn) & " bytes)" severity failure;
            dn := 0; dh := 0;
            for k in 0 to 16 loop dpush(x"EE"); end loop;
         end if;         if CD_STRAY and want_load = '1' and not loading then
            flag := "00011"; push(x"00"); stray2 := true;   -- GetID's INT3 (stat, motor still off), then its INT2
         end if;
         loading := want_load = '1';
         if motor_left > 0 then
            motor_left := motor_left - 1;
            if motor_left = 0 then motor := true; end if;
         end if;
         -- the drive reads on
         if busy_left > 0 then busy_left := busy_left - 1; end if;
         if (reading or playing) and motor then
            if sector_left > 0 then sector_left := sector_left - 1;
            else
               sector_left := 4000; lba := lba + 1; busy_left := 300;
               -- during a load, before its ReadN, a sector raises INT1 (Data Ready) when the flags are
               -- clear: the handler must skip it, not take it as the answer to its own command
               if want_load = '1' and not readn_seen and flag = "00000" then flag := "00001"; push(stat); end if;
            end if;
         end if;
         if stray2 and flag = "00000" then
            stray2 := false; flag := "00010";
            push(x"02"); push(x"00"); push(x"20"); push(x"00"); push(x"53"); push(x"43"); push(x"45"); push(x"45");
         end if;
         -- the command, once the flags are clear
         if cmd_left > 1 then cmd_left := cmd_left - 1;
         elsif cmd_left = 1 and flag = "00000" then
            cmd_left := 0;
            flag := "00011";
            case cmd is
               when x"01" => push(stat);
               when x"09" => push(stat); reading := false; playing := false; int2_left := 3000;
               when x"0E" => mode := par(0); push(stat);
               when x"0D" => xfile := par(0); xchan := par(1); push(stat);
               when x"0C" => demuted := true; push(stat);
               when x"02" =>
                  target := (bcd(par(0)) * 60 + bcd(par(1))) * 75 + bcd(par(2)); setloc_seen := true; push(stat);   -- MSF in sectors, 00:02:00 = 150, as cd_top's seekLBA and its tap LBA (drive-state.md)
               when x"06" =>
                  assert setloc_seen report "ReadN without Setloc" severity failure;
                  reading := true; lba := target - 1; sector_left := 20000; busy_left := 0; readn_seen := true;
                  push(stat);
               when x"03" => playing := true; lba := target; push(stat);
               when others =>
                  report "unexpected CD command " & to_hstring(cmd) severity failure;
            end case;
            par_n := 0;
         end if;
         if int2_left > 1 then int2_left := int2_left - 1;
         elsif int2_left = 1 and flag = "00000" then int2_left := 0; flag := "00010"; push(stat); end if;
         -- registers
         if ce = '1' and mux_bus_cd_read = '1' then
            a := to_integer(mux_bus_cd_addr(1 downto 0));
            case a is
               when 0 =>
                  cd_q <= (others => '0');
                  if cmd_left > 0 then cd_q(7) <= '1'; end if;
                  if resp_n > 0 then cd_q(5) <= '1'; end if;
                  if dn > 0 then cd_q(6) <= '1'; end if;
                  cd_q(4) <= '1';
                  if par_n = 0 then cd_q(3) <= '1'; end if;
                  cd_q(1 downto 0) <= std_logic_vector(to_unsigned(idx, 2));
               when 1 =>
                  if resp_n > 0 then cd_q <= resp(resp_rd); resp_rd := (resp_rd + 1) mod 16; resp_n := resp_n - 1; end if;
               when 2 =>
                  if dn > 0 then cd_q <= dfifo(dh); dh := (dh + 1) mod 4096; dn := dn - 1; end if;
               when 3 =>
                  if idx mod 2 = 1 then cd_q <= "111" & flag; else cd_q <= "111" & irqena; end if;
               when others => null;
            end case;
         end if;
         if ce = '1' and mux_bus_cd_write = '1' then
            a := to_integer(mux_bus_cd_addr(1 downto 0)); d := mux_bus_cd_dataWrite;
            if a = 0 then idx := to_integer(unsigned(d(1 downto 0)));
            elsif a = 1 and idx = 0 then
               assert want_load = '1' report "CD command " & to_hstring(d) & " outside a load" severity failure;
               assert cmd_left = 0 report "CD command while one runs" severity failure;
               cmd := d; cmd_left := 1500; int2_left := 0; ncmd := ncmd + 1;
            elsif a = 2 and idx = 0 then
               par(par_n) := d; par_n := par_n + 1;
            elsif a = 2 and idx = 1 then irqena := d(4 downto 0);
            elsif a = 3 and idx = 0 then
               if d(7) = '0' then dn := 0; dh := 0; end if;   -- request register: BFRD 0 empties the data FIFO
            elsif a = 3 and idx = 1 then
               flag := flag and not d(4 downto 0);
               if d(6) = '1' then par_n := 0; end if;
            end if;
         end if;
         -- a finished load: the drive set up as the game had it
         -- (a load that ends with no CD command since the last one is a load refused after the
         -- early-load answer, whose exit the bench counts as the load's end: nothing to check;
         -- drive-state.md)
         if loads_done /= last_loads and ncmd = ncmd_seen then
            last_loads := loads_done;
            report "load: ended with no CD access (refused after the early answer)" severity note;
         elsif loads_done /= last_loads then
            last_loads := loads_done; ncmd_seen := ncmd;
            assert mode = GAME_MODE and xfile = GAME_FILE and xchan = GAME_CHAN
               report "load: CD mode/filter not restored" severity failure;
            assert readn_seen and reading and target = cd_capt + 1
               report "load: ReadN from " & integer'image(target) & ", the save had read up to " & integer'image(cd_capt)
               severity failure;
            assert irqena = "11111" and idx = 1 report "load: CD IRQENA / index not restored" severity failure;
            assert demuted report "load: no Demute" severity failure;
            -- nothing left for the restored game: no flag, no response byte, nothing queued or on its way
            assert flag = "00000" and resp_n = 0 and not stray2 and cmd_left = 0 and int2_left = 0
               report "load: a CD response left for the game (flag " & to_hstring(flag) & ", " & integer'image(resp_n) & " bytes)"
               severity failure;
            assert left_ok report "load: the CD data FIFO is not the state's (" & integer'image(dn) & " bytes)" severity failure;
            report "load: CD reads on from " & integer'image(target) severity note;
            setloc_seen := false; readn_seen := false;
         end if;
         busy := '0';
         if cmd_left > 0 or int2_left > 0 or busy_left > 0 or stray2 then busy := '1'; end if;
         cd_state_s <= "0000000" & busy & std_logic_vector(to_unsigned(lba, 24)) & xchan & xfile & mode & stat;
      end if;
   end process;

   -- ---------------- GPU model ----------------
   bus_gpu_dataRead <= gpu_q;
   bus_gpu_stall <= gpu_stall;
   process (clk1x)
      variable vram : words(0 to VRAM_ROWS * 512 - 1);
      variable initialised : boolean := false;
      variable e1 : std_logic_vector(11 downto 0) := (others => '0');
      variable mask : std_logic_vector(1 downto 0) := "00";
      variable mode : std_logic_vector(7 downto 0) := (others => '0');
      variable dma : std_logic_vector(1 downto 0) := "00";
      variable disp_off, irq : std_logic := '0';
      variable tw, e3, e4, e5, gpuread : std_logic_vector(31 downto 0) := (others => '0');
      variable vrange : std_logic_vector(18 downto 0) := (others => '0');
      variable hrange : std_logic_vector(23 downto 0) := (others => '0');
      variable vdrange : std_logic_vector(19 downto 0) := (others => '0');
      variable cmd : std_logic_vector(7 downto 0) := (others => '0');
      variable params, pixels_in, pixels_out, k : natural := 0;
      variable rx, ry, rw, rh : natural := 0;
      variable value, d, stat : std_logic_vector(31 downto 0);
      variable pending : boolean := false;
      variable wait_left : natural := 0;
      variable half : std_logic_vector(15 downto 0);
      procedure pixel_at(n : natural; variable index : out natural; variable high : out boolean) is
         variable x, y : natural;
      begin
         x := (rx + n mod rw) mod 1024; y := (ry + n / rw) mod VRAM_ROWS;
         index := y * 512 + x / 2; high := x mod 2 = 1;
      end procedure;
      procedure put(v : std_logic_vector(15 downto 0)) is
         variable index : natural; variable high : boolean;
      begin
         pixel_at(k, index, high);
         if high then vram(index)(31 downto 16) := v; else vram(index)(15 downto 0) := v; end if;
         k := k + 1;
      end procedure;
      procedure get(variable v : out std_logic_vector(15 downto 0)) is
         variable index : natural; variable high : boolean;
      begin
         pixel_at(k, index, high);
         k := k + 1;
         if high then v := vram(index)(31 downto 16); else v := vram(index)(15 downto 0); end if;
      end procedure;
      procedure reset_gpu is
      begin
         e1 := (others => '0'); mask := "00"; mode := (others => '0'); dma := "00"; disp_off := '1'; irq := '0';
         tw := (others => '0'); e3 := (others => '0'); e4 := (others => '0'); e5 := (others => '0');
         vrange := (others => '0'); hrange := (others => '0'); vdrange := (others => '0');
         params := 0; pixels_in := 0; pixels_out := 0;
      end procedure;
   begin
      if rising_edge(clk1x) then
         if not initialised then
            for i in vram'range loop vram(i) := std_logic_vector(to_unsigned((i * 7919 + SEED * 104729) mod 2**30, 32)); end loop;
            for i in 0 to 511 loop vram(ZERO_ROW * 512 + i) := (others => '0'); end loop;   -- (the game draws in rows 0-3)
            initialised := true;
         end if;
         gpu_q <= (others => '0');
         if pending then
            if wait_left <= 1 then gpu_q <= value; gpu_stall <= '0'; pending := false;
            else wait_left := wait_left - 1; end if;
         end if;
         if reset = '0' and mux_bus_gpu_read = '1' then
            assert not pending report "GPU read while a read waits" severity failure;
            if mux_bus_gpu_addr(2) = '1' then
               value := stat;
            elsif pixels_out > 0 then
               get(half); value(15 downto 0) := half; get(half); value(31 downto 16) := half; pixels_out := pixels_out - 1;
            else
               value := gpuread;
            end if;
            wait_left := to_integer(lfsr(1 downto 0));
            if wait_left = 0 then gpu_q <= value; gpu_stall <= '0';
            else gpu_stall <= '1'; pending := true; end if;
         end if;
         if reset = '0' and mux_bus_gpu_write = '1' then
            d := mux_bus_gpu_dataWrite;
            if mux_bus_gpu_addr(2) = '1' then                 -- GP1
               case to_integer(unsigned(d(29 downto 24))) is
                  when 16#00# => reset_gpu;
                  when 16#01# => params := 0; pixels_in := 0;
                  when 16#02# => irq := '0';
                  when 16#03# => disp_off := d(0);
                  when 16#04# => dma := d(1 downto 0);
                  when 16#05# => vrange := d(18 downto 1) & '0';
                  when 16#06# => hrange := d(23 downto 0);
                  when 16#07# => vdrange := d(19 downto 0);
                  when 16#08# => mode := d(7 downto 0);
                  when 16#10# to 16#1F# =>
                     case to_integer(unsigned(d(2 downto 0))) is
                        when 2 => gpuread := tw;
                        when 3 => gpuread := e3;
                        when 4 => gpuread := e4;
                        when 5 => gpuread := e5;
                        when others => null;
                     end case;
                  when others => report "GPU model: GP1 " & to_hstring(d) severity failure;
               end case;
            elsif pixels_in > 0 then                         -- GP0 data
               put(d(15 downto 0)); put(d(31 downto 16)); pixels_in := pixels_in - 1;
            elsif params > 0 then
               if params = 2 then rx := to_integer(unsigned(d(9 downto 0))); ry := to_integer(unsigned(d(24 downto 16)));
               else
                  rw := to_integer(unsigned(d(10 downto 0))); rh := to_integer(unsigned(d(25 downto 16)));
                  if rw = 0 then rw := 1024; end if;
                  if rh = 0 then rh := 512; end if;
                  k := 0;
                  if cmd = x"A0" then pixels_in := (rw * rh + 1) / 2; else pixels_out := (rw * rh + 1) / 2; end if;
               end if;
               params := params - 1;
            else
               cmd := d(31 downto 24);
               case cmd is
                  when x"00" | x"01" => null;
                  when x"1F" => irq := '1';
                  when x"A0" | x"C0" => params := 2;
                  when x"E1" => e1 := d(11 downto 0);
                  when x"E2" => tw := x"000" & d(19 downto 0);
                  when x"E3" => e3 := x"000" & '0' & d(18 downto 0);
                  when x"E4" => e4 := x"000" & '0' & d(18 downto 0);
                  when x"E5" => e5 := x"00" & "00" & d(21 downto 0);
                  when x"E6" => mask := d(1 downto 0);
                  when others => report "GPU model: GP0 " & to_hstring(d) severity failure;
               end case;
            end if;
         end if;
         stat := (others => '0');
         stat(10 downto 0) := e1(10 downto 0); stat(15) := e1(11); stat(12 downto 11) := mask(1) & mask(0);
         stat(18 downto 17) := mode(1 downto 0); stat(22 downto 19) := mode(5 downto 2);
         stat(16) := mode(6); stat(14) := mode(7);
         stat(23) := disp_off; stat(24) := irq; stat(30 downto 29) := dma; stat(28) := '1';
         -- (GPU_HOLD / VRAM_SEND only while the routine runs: the game must run as in the reference)
         if params = 0 and pixels_in = 0 and not (GPU_HOLD > 0 and in_handler = '1' and cycle_count >= SAVE_AT and cycle_count < SAVE_AT + GPU_HOLD) then
            stat(26) := '1';
         end if;
         if pixels_out > 0 or (VRAM_SEND and in_handler = '1') then stat(27) := '1'; end if;
         gpu_stat_s <= stat; gpu_tw <= tw; gpu_e3 <= e3; gpu_e4 <= e4; gpu_e5 <= e5;
         gpu_ranges <= vdrange & hrange & vrange;
         gpu_vram <= vram;
      end if;
   end process;

   -- ---------------- SDRAM model (tb_memorymux_fifo_cpu.vhd) ----------------
   process (clk3x)
      variable mem : words(0 to 524287) := load("ram.hex", 524288, true);
      -- SDRAM 0x200000-0x20FFFF: stage 2 of the save routine (psx_top: the CPU's
      -- bits 22:21 reach it in save mode; main RAM's mirror otherwise)
      variable high : words(0 to 16383) := (others => (others => '0'));
      variable warm_done : boolean := false;
      variable s1 : positive := 77 + SEED;
      variable s2 : positive := 9001 + SEED;
      variable r : real;
      variable pending, fill, finishing : boolean := false;
      variable delay, word_index, start_word, index : natural := 0;
      variable adr : std_logic_vector(24 downto 0);
      variable rnw : std_logic;
      variable be : std_logic_vector(3 downto 0);
      variable wdata, value : std_logic_vector(31 downto 0);
      variable at_cpu_edge : boolean;
      file dump : text;
      variable row : line;

      impure function in_high(a : std_logic_vector(24 downto 0)) return boolean is
      begin
         if a(24 downto 23) = "00" and save_mode_s = '1' and a(22 downto 21) /= "00" then
            assert a(22 downto 16) = "0100000" report "save mode access outside stage 2's SDRAM" severity failure;
            return true;
         end if;
         return false;
      end function;
      impure function fetch(a : std_logic_vector(24 downto 0)) return std_logic_vector is
      begin
         if in_high(a) then
            return high(to_integer(unsigned(a(15 downto 2))));
         elsif a(24 downto 23) = "00" then
            return mem(to_integer(unsigned(a(20 downto 2))));
         elsif a(24 downto 23) = "01" and unsigned(a(18 downto 9)) = 0 then
            return rom(to_integer(unsigned(a(8 downto 2))));
         else
            return x"00000000";
         end if;
      end function;
   begin
      if rising_edge(clk3x) then
         if STAGE2_WARM and not warm_done then
            high(0 to 2047) := load("stage2.hex", 2048, false);
            warm_done := true;
         end if;
         at_cpu_edge := clk1x = '1' and clk1x'last_event = 0 ns;
         cache_wr <= "0000";
         if at_cpu_edge then
            ram_cpu_done <= '0';
         end if;
         if finishing then
            ram_cpu_done <= '1'; pending := false; finishing := false;
         elsif pending and fill and delay = 0 and not at_cpu_edge then
            value := fetch(adr(24 downto 4) & std_logic_vector(to_unsigned(word_index, 2)) & "00");
            cache_data <= value;
            cache_addr <= adr(11 downto 4);
            cache_wr <= std_logic_vector(shift_left(to_unsigned(1, 4), word_index));
            if word_index = start_word then ram_data <= value; end if;
            if word_index = 3 then finishing := true; else word_index := word_index + 1; end if;
         end if;
         if at_cpu_edge and reset = '0' then
            if pending and not fill and not finishing then
               if delay > 0 then
                  delay := delay - 1;
               else
                  if rnw = '1' then
                     ram_data <= fetch(adr);
                  elsif in_high(adr) then
                     index := to_integer(unsigned(adr(15 downto 2)));
                     for b in 0 to 3 loop
                        if be(b) = '1' then high(index)(8*b+7 downto 8*b) := wdata(8*b+7 downto 8*b); end if;
                     end loop;
                  elsif adr(24 downto 23) = "00" then
                     index := to_integer(unsigned(adr(20 downto 2)));
                     for b in 0 to 3 loop
                        if be(b) = '1' then mem(index)(8*b+7 downto 8*b) := wdata(8*b+7 downto 8*b); end if;
                     end loop;
                  end if;
                  ram_cpu_done <= '1'; pending := false;
               end if;
            elsif pending and fill and delay > 0 then
               delay := delay - 1;
            end if;
            if mux_ram_ena = '1' then
               assert not pending report "memorymux issued ram_ena while busy" severity failure;
               uniform(s1, s2, r);
               adr := mux_ram_Adr; rnw := mux_ram_rnw; be := mux_ram_be; wdata := mux_ram_dataWrite;
               -- a save reads main RAM only (stage 2's SDRAM is apart from it)
               assert not (rnw = '0' and want_save = '1' and in_handler = '1' and not in_high(adr) and adr(24 downto 23) = "00")
                  report "the save routine wrote main RAM at " & to_hstring(adr) severity failure;
               pending := true; delay := natural(floor(r * 5.0)) mod 5;
               fill := mux_ram_cache = '1' and rnw = '1';
               start_word := to_integer(unsigned(adr(3 downto 2))); word_index := start_word;
               if rnw = '0' and unsigned(adr(24 downto 12)) = 3 then log_stores <= log_stores + 1; end if;
               if rnw = '0' and unsigned(adr) = 16#FF00# and wdata = x"600DF00D" and finished = '0' then
                  finished <= '1';
                  file_open(dump, "dump.hex", write_mode);
                  for k in 0 to DUMP_BYTES / 4 - 1 loop
                     hwrite(row, mem(k)); writeline(dump, row);
                  end loop;
                  for k in 0 to 6 loop
                     case k is
                        when 0 => value := gpu_stat_s;
                        when 1 => value := gpu_tw;
                        when 2 => value := gpu_e3;
                        when 3 => value := gpu_e4;
                        when 4 => value := gpu_e5;
                        when 5 => value := gpu_ranges(31 downto 0);
                        when others => value := '0' & gpu_ranges(62 downto 32);
                     end case;
                     hwrite(row, value); writeline(dump, row);
                  end loop;
                  for k in gpu_vram'range loop
                     hwrite(row, gpu_vram(k)); writeline(dump, row);
                  end loop;
                  for k in 0 to 127 loop hwrite(row, spu_regs_s(2 * k + 1) & spu_regs_s(2 * k)); writeline(dump, row); end loop;
                  for k in 0 to SPU_PAGES * 512 - 1 loop hwrite(row, spu_ram_s(2 * k + 1) & spu_ram_s(2 * k)); writeline(dump, row); end loop;
                  file_close(dump);
                  report "STATS save trap seed=" & integer'image(SEED) & " cycles=" & integer'image(cycle_count) &
                     " retired=" & integer'image(retired) & " log_stores=" & integer'image(log_stores) &
                     " dma_bursts=" & integer'image(dma_bursts) & " saves=" & integer'image(saves_done) & " saves_failed=" & integer'image(saves_failed) &
                     " loads=" & integer'image(loads_done) &
                     " loads_failed=" & integer'image(loads_failed) & " handler_fetches=" & integer'image(handler_fetches) &
                     " retries=" & integer'image(retries) & " spu_writes=" & integer'image(spu_guest_writes) & " spu_rekeys=" & integer'image(spu_rekeys);
                  assert trap = '0' and want_save = '0' and want_load = '0' report "request still open at the finish" severity failure;
                  assert spu_hold = '0' report "SPU still held at the finish" severity failure;
                  report "PASS save trap run";
                  finish;
               end if;
            end if;
         end if;
      end if;
   end process;

end architecture;
