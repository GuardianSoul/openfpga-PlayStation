-- CPU-assisted save states (scripts/prepare_save_states.py): the MiSTer CPU
-- and memorymux with the trap and EXP1 transforms, an SDRAM model (from
-- tb_memorymux_fifo_cpu.vhd), and an EXP1 device model with the register map
-- of rtl/pocket/psx_save_exp1.sv: the handler ROM (rom_exp1.hex), a staging
-- page, page copies to and from a save buffer, STATUS/ACK/FINISH and the trap.
-- A generated game program (ram.hex, started by rom.hex) runs with IEc=1.
-- SAVE_AT / LOAD_AT (clk1x cycles, 0 = never) raise a save or load request.
-- A GPU model (GPUSTAT fields, GP0 E1-E6 / A0 / C0 / 1F, GP1 00-08 / 10h,
-- VRAM_ROWS rows of 1024 pixels, reads stalled 0-3 cycles) gives the handler's
-- quiet-point check, GPU settings and VRAM copies something to work on.
-- An SPU model (in the EXP1 process: the SPU bus, its savestate port and SPU
-- RAM) changes port words and SPU RAM with every guest register write, holds
-- like the tapped SPU (quiet some cycles after SPU_HOLD) and gives guest
-- writes made while held the side effects the savestate port writes repair.
-- At the finish marker the bench writes RAM 0..DUMP_BYTES-1, the GPU state,
-- VRAM and the SPU state to dump.hex; the runner compares dumps between runs. Declarations, instances and stubs are
-- generated by scripts/run_save_trap_cpu.py.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;
use std.textio.all;
use std.env.all;
use work.pexport.all;

entity tb_save_trap_cpu is
   generic
   (
      SEED       : positive := 1;
      SAVE_AT    : natural  := 0;
      LOAD_AT    : natural  := 0;
      BUF_PAGES  : positive := 24;    -- buffer pages kept; page 2047 maps to the last one
      DUMP_BYTES : positive := 16384;
      MAX_CYCLES : natural  := 3000000;
      PROGRESS   : natural  := 0;
      VRAM_ROWS  : positive := 4;
      SPU_PAGES  : positive := 2;     -- SPU RAM pages of 1024 halfwords (ROM word 0xFF4)
      GPU_HOLD   : natural  := 0;     -- the GPU reports a command in progress for this long from SAVE_AT
      LOAD_DISC  : natural  := 0      -- the disc in the drive (0x180B) during a load; 0 while saving
   );
end entity;

architecture test of tb_save_trap_cpu is
   type words is array(natural range <>) of std_logic_vector(31 downto 0);
   impure function load(path : string; size : positive; sparse : boolean) return words is
      file data : text open read_mode is path;
      variable row : line;
      variable result : words(0 to size - 1) := (others => (others => '0'));
      variable address : std_logic_vector(31 downto 0);
      variable index : natural := 0;
   begin
      while not endfile(data) loop
         readline(data, row);
         if sparse then hread(row, address); index := to_integer(unsigned(address)) / 4; end if;
         assert index < size report "image exceeds memory" severity failure;
         hread(row, result(index)); index := index + 1;
      end loop;
      return result;
   end function;
   constant rom : words(0 to 127) := load("rom.hex", 128, false);
   constant exp1_rom : words(0 to 1023) := load("rom_exp1.hex", 1024, false);

   signal clk1x, clk2x, clk3x : std_logic := '1';
   signal reset, ss_reset : std_logic := '1';
   signal ce : std_logic := '1';
   signal cpuPaused, pause_next : std_logic := '0';
   signal ram_data : std_logic_vector(31 downto 0) := (others => '0');
   signal ram_cpu_done : std_logic := '0';
   signal cache_wr : std_logic_vector(3 downto 0) := "0000";
   signal cache_data : std_logic_vector(31 downto 0) := (others => '0');
   signal cache_addr : std_logic_vector(7 downto 0) := (others => '0');
   signal lfsr : unsigned(63 downto 0) := x"0123456789ABCDEF";
   signal finished : std_logic := '0';

   -- EXP1 device model
   signal trap, want_save, want_load, cp_busy : std_logic := '0';
   signal exp1_q : std_logic_vector(7 downto 0) := (others => '0');
   signal finish_code : natural := 0;
   signal saves_done, saves_failed, loads_done, loads_failed, handler_fetches, retries : natural := 0;

   -- GPU model
   signal gpu_vram : words(0 to VRAM_ROWS * 512 - 1);
   signal gpu_stat_s : std_logic_vector(31 downto 0) := (others => '0');
   signal gpu_tw, gpu_e3, gpu_e4, gpu_e5 : std_logic_vector(31 downto 0) := (others => '0');
   signal gpu_ranges : std_logic_vector(62 downto 0) := (others => '0');
   signal gpu_q : std_logic_vector(31 downto 0) := (others => '0');
   signal gpu_stall : std_logic := '0';

   -- SPU model
   type halves is array(natural range <>) of std_logic_vector(15 downto 0);
   signal spu_hold, spu_quiet, ss_busy : std_logic := '0';
   signal spu_q : std_logic_vector(15 downto 0) := (others => '0');
   signal spu_regs_s : halves(0 to 255);
   signal spu_ss_s : words(0 to 511);
   signal spu_ram_s : halves(0 to SPU_PAGES * 1024 - 1);
   signal spu_guest_writes : natural := 0;

   signal cycle_count, retired, log_stores : natural := 0;
   signal clk1xToggle, clk1xToggle2x, clk2xIndex, gte_busy : std_logic := '0';
   signal gte_readData : unsigned(31 downto 0);

   -- GENERATED_DECLARATIONS
begin

   clk1x <= not clk1x after 15 ns;
   clk2x <= not clk2x after 7500 ps;
   clk3x <= not clk3x after 5 ns;

   pause_next <= cpuPaused;

   -- psx_top's clk2xIndex (the GTE's clk2x phase)
   process (clk1x) begin if rising_edge(clk1x) then clk1xToggle <= not clk1xToggle; end if; end process;
   process (clk2x)
   begin
      if rising_edge(clk2x) then
         clk1xToggle2x <= clk1xToggle;
         clk2xIndex <= '0';
         if clk1xToggle2x = clk1xToggle then clk2xIndex <= '1'; end if;
      end if;
   end process;

   -- GENERATED_INSTANCES

   process
   begin
      for edge in 1 to 4 loop wait until falling_edge(clk1x); end loop;
      ss_reset <= '0';
      for edge in 1 to 50 loop wait until falling_edge(clk1x); end loop;
      reset <= '0';
      wait;
   end process;

   process (clk1x)
   begin
      if rising_edge(clk1x) then
         cycle_count <= cycle_count + 1;
         assert cycle_count < MAX_CYCLES report "program did not finish" severity failure;
         lfsr <= lfsr(62 downto 0) & (lfsr(63) xor lfsr(62) xor lfsr(60) xor lfsr(59));
         -- GENERATED_STUBS
         if PROGRESS > 0 and cycle_count mod PROGRESS = 0 then
            report "progress cycles=" & integer'image(cycle_count) & " retired=" & integer'image(retired) &
               " log_stores=" & integer'image(log_stores) & " pc=" & to_hstring(cpu_cpu_export.pc);
         end if;
         if reset = '0' and ce = '1' and cpu_cpu_done = '1' then
            retired <= retired + 1;
            assert cpu_cpu_export.pc /= x"80000080" and cpu_cpu_export.pc /= x"BFC00180"
               report "program took a normal exception: cause=" & to_hstring(cpu_cpu_export.cause) &
                  " epc(r) k0=" & to_hstring(cpu_cpu_export.regs(26)) & " ra=" & to_hstring(cpu_cpu_export.regs(31))
               severity failure;
         end if;
         if reset = '0' and ce = '1' and cpu_cpu_done = '1' and cpu_cpu_export.pc(31 downto 12) = x"BF000" then
            assert std_logic_vector(cpu_cpu_export.opcode) = exp1_rom(to_integer(cpu_cpu_export.pc(11 downto 2)))
               report "handler opcode at " & to_hstring(cpu_cpu_export.pc) & " is " & to_hstring(cpu_cpu_export.opcode) &
                  ", ROM has " & to_hstring(exp1_rom(to_integer(cpu_cpu_export.pc(11 downto 2)))) severity failure;
         end if;
         if reset = '0' and cpu_mem_request = '1' and cpu_mem_isData = '0' and
            cpu_mem_addressInstr(31 downto 12) = x"BF000" then
            handler_fetches <= handler_fetches + 1;
         end if;
      end if;
   end process;

   -- ---------------- EXP1 device model ----------------
   -- Read data is registered on clk2x from the bus address (the device's
   -- M10K timing); writes are taken on clk1x when bus_exp1_write is high.
   process (clk2x)
      variable page : words(0 to 511) := (others => (others => '0'));
      variable buf : words(0 to BUF_PAGES * 512 - 1) := (others => x"DEADBEEF");
      variable a : natural;
      variable w : std_logic_vector(31 downto 0);
      variable page_lo, page_hi : natural := 0;
      variable p, busy_left, retry_left : natural := 0;
      variable at_cpu_edge : boolean;
      variable regs : halves(0 to 255) := (others => (others => '0'));
      variable ss : words(0 to 511) := (others => (others => '0'));
      variable spuram : halves(0 to SPU_PAGES * 1024 - 1) := (others => (others => '0'));
      variable ss_adr, ss_left, quiet_left, sa, sk : natural := 0;
      variable sd : std_logic_vector(15 downto 0);
      variable initialised : boolean := false;
      -- the port words a save keeps (tb_spu_save_tap.vhd ss_saved)
      function ss_saved(n : natural) return boolean is
      begin
         return (n >= 2 and n <= 6) or n = 37 or n = 40 or n = 43 or (n >= 256 and n < 304) or
                (n >= 320 and n < 370) or (n >= 384 and n < 480);
      end function;
      -- registers a load does not write back (tb_spu_save_tap.vhd bus_restored)
      function spu_skipped(a : natural) return boolean is
      begin
         return a = 16#19C# or a = 16#19E# or a = 16#1A8# or a = 16#1AE# or a = 16#1B8# or a = 16#1BA#;
      end function;
      impure function slot(n : natural) return natural is
      begin
         if n = 2047 then return BUF_PAGES - 1; end if;
         assert n < BUF_PAGES - 1 report "save page " & integer'image(n) & " outside the model buffer" severity failure;
         return n;
      end function;
   begin
      if rising_edge(clk2x) then
         at_cpu_edge := clk1x = '1' and clk1x'last_event = 0 ns;
         a := to_integer(mux_bus_exp1_addr);
         if a < 16#1000# then
            w := exp1_rom(a / 4);
            exp1_q <= w(8 * (a mod 4) + 7 downto 8 * (a mod 4));
         elsif a < 16#1800# then
            w := page((a - 16#1000#) / 4);
            exp1_q <= w(8 * (a mod 4) + 7 downto 8 * (a mod 4));
         elsif a = 16#1800# then
            exp1_q <= "00000" & want_load & want_save & cp_busy;
         elsif a >= 16#1810# and a < 16#1818# then
            w := gpu_ranges(31 downto 0);
            if a >= 16#1814# then w := '0' & gpu_ranges(62 downto 32); end if;
            exp1_q <= w(8 * (a mod 4) + 7 downto 8 * (a mod 4));
         elsif a = 16#180B# then
            if want_load = '1' then exp1_q <= std_logic_vector(to_unsigned(LOAD_DISC, 8)); else exp1_q <= x"00"; end if;
         elsif a = 16#180C# then
            exp1_q <= "0000000" & spu_quiet;
         elsif a = 16#180F# then
            exp1_q <= "0000000" & ss_busy;
         else
            exp1_q <= x"00";
         end if;
         if retry_left > 0 and at_cpu_edge then
            retry_left := retry_left - 1;
            if retry_left = 0 then trap <= '1'; end if;
         end if;
         if busy_left > 0 then
            busy_left := busy_left - 1;
            if busy_left = 0 then cp_busy <= '0'; end if;
         end if;
         -- SPU model: quiet a while after the hold, port accesses take a few cycles
         if not initialised then
            for i in 0 to 511 loop if ss_saved(i) then ss(i) := std_logic_vector(to_unsigned((i * 2654435 + SEED) mod 2**30, 32)); end if; end loop;
            initialised := true;
         end if;
         if spu_hold = '0' then spu_quiet <= '0'; quiet_left := 100 + to_integer(lfsr(10 downto 0));
         elsif quiet_left > 0 then quiet_left := quiet_left - 1;
         else spu_quiet <= '1'; end if;
         if ss_left > 0 then
            ss_left := ss_left - 1;
            if ss_left = 0 then ss_busy <= '0'; end if;
         end if;
         if at_cpu_edge and ce = '1' and mux_bus_spu_read = '1' then
            sa := to_integer(mux_bus_spu_addr);
            spu_q <= (others => '0');
            if sa < 16#200# and not spu_skipped(sa) then spu_q <= regs(sa / 2); end if;
            -- the current main volume reads back what port word 43 sets
            if sa = 16#1B8# then spu_q <= ss(43)(15 downto 0); end if;
            if sa = 16#1BA# then spu_q <= ss(43)(31 downto 16); end if;
         end if;
         if at_cpu_edge and ce = '1' and mux_bus_spu_write = '1' then
            sa := to_integer(mux_bus_spu_addr); sd := mux_bus_spu_dataWrite;
            if spu_hold = '0' then
               -- a guest write: the register, plus one port word and one SPU RAM halfword
               if sa < 16#200# and not spu_skipped(sa) then regs(sa / 2) := sd; end if;
               sk := (sa * 31 + to_integer(unsigned(sd))) mod 512;
               while not ss_saved(sk) loop sk := (sk + 1) mod 512; end loop;
               ss(sk) := std_logic_vector(rotate_left(unsigned(ss(sk)), 7)) xor (sd & std_logic_vector(to_unsigned(sa, 16)));
               spuram((to_integer(unsigned(sd)) * 7 + sa) mod (SPU_PAGES * 1024)) := sd xor std_logic_vector(to_unsigned(sa, 16));
               spu_guest_writes <= spu_guest_writes + 1;
            else
               assert sa < 16#200# report "handler wrote SPU register " & to_hstring(to_unsigned(sa, 12)) severity failure;
               assert spu_quiet = '1' report "SPU register write before the quiet point" severity failure;
               assert not spu_skipped(sa) report "handler wrote SPU register " & to_hstring(to_unsigned(sa, 12)) severity failure;
               if not spu_skipped(sa) then regs(sa / 2) := sd; end if;
               -- side effects of guest writes the port writes after them repair
               if sa = 16#1A2# then ss(4) := x"BAD00004"; end if;    -- mBASE: the reverb pointer
               if sa = 16#1A6# then ss(3) := x"BAD00003"; end if;    -- transfer address
               if sa = 16#1AA# then ss(40) := x"BAD00040"; end if;   -- SPUCNT: the IRQ line
            end if;
         end if;
         if at_cpu_edge and ce = '1' and mux_bus_exp1_write = '1' then
            if a >= 16#1000# and a < 16#1800# then
               page((a - 16#1000#) / 4)(8 * (a mod 4) + 7 downto 8 * (a mod 4)) := mux_bus_exp1_dataWrite;
            elsif a = 16#1800# and mux_bus_exp1_dataWrite(2) = '1' then
               assert cp_busy = '0' report "COMMAND while a copy runs" severity failure;
               assert spu_hold = '1' and spu_quiet = '1' report "SPU RAM copy while the SPU runs" severity failure;
               assert page_lo < SPU_PAGES report "SPU RAM page outside the model" severity failure;
               for k in 0 to 511 loop
                  if mux_bus_exp1_dataWrite(1) = '1' then
                     page(k) := spuram(page_lo * 1024 + 2 * k + 1) & spuram(page_lo * 1024 + 2 * k);
                  else
                     spuram(page_lo * 1024 + 2 * k) := page(k)(15 downto 0);
                     spuram(page_lo * 1024 + 2 * k + 1) := page(k)(31 downto 16);
                  end if;
               end loop;
               cp_busy <= '1'; busy_left := 200 + to_integer(lfsr(7 downto 0));
            elsif a = 16#1800# then
               assert cp_busy = '0' report "COMMAND while a copy runs" severity failure;
               if mux_bus_exp1_dataWrite(0) = '1' then
                  p := slot(page_hi * 256 + page_lo);
                  for k in 0 to 511 loop
                     if mux_bus_exp1_dataWrite(1) = '1' then page(k) := buf(p * 512 + k);
                     else buf(p * 512 + k) := page(k); end if;
                  end loop;
                  cp_busy <= '1'; busy_left := 20 + to_integer(lfsr(5 downto 0));
               end if;
            elsif a = 16#1801# then
               page_lo := to_integer(unsigned(mux_bus_exp1_dataWrite));
            elsif a = 16#1802# then
               page_hi := to_integer(unsigned(mux_bus_exp1_dataWrite(2 downto 0)));
            elsif a = 16#1803# and mux_bus_exp1_dataWrite(2) = '1' then
               trap <= '0'; retry_left := 3000; retries <= retries + 1;
            elsif a = 16#1803# then
               if want_save = '1' then
                  if mux_bus_exp1_dataWrite(0) = '1' then saves_done <= saves_done + 1;
                  else saves_failed <= saves_failed + 1; end if;
               elsif want_load = '1' then
                  if mux_bus_exp1_dataWrite(0) = '1' then loads_done <= loads_done + 1;
                  else loads_failed <= loads_failed + 1; end if;
               end if;
               want_save <= '0'; want_load <= '0';
               finish_code <= to_integer(unsigned(mux_bus_exp1_dataWrite));
               if want_save = '1' then
                  report "save taken at EPC " & to_hstring(buf(36)) severity note;
               end if;
            elsif a = 16#1804# then
               trap <= '0';
            elsif a = 16#180C# then
               spu_hold <= mux_bus_exp1_dataWrite(0);
            elsif a = 16#180D# then
               ss_adr := ss_adr - ss_adr mod 256 + to_integer(unsigned(mux_bus_exp1_dataWrite));
            elsif a = 16#180E# then
               ss_adr := ss_adr mod 256 + 256 * to_integer(unsigned(mux_bus_exp1_dataWrite(0 downto 0)));
            elsif a = 16#180F# and mux_bus_exp1_dataWrite(1 downto 0) /= "00" then
               assert ss_busy = '0' report "SS command while one runs" severity failure;
               assert spu_hold = '1' and spu_quiet = '1' report "SPU port access while the SPU runs" severity failure;
               assert ss_saved(ss_adr) report "SPU port word " & integer'image(ss_adr) & " is not one a save keeps" severity failure;
               -- the port word goes through staging page word ss_adr
               -- (word 43, the current main volume, reads as 0 like the tapped SPU)
               if mux_bus_exp1_dataWrite(1) = '1' then ss(ss_adr) := page(ss_adr);
               elsif ss_adr = 43 then page(ss_adr) := (others => '0');
               else page(ss_adr) := ss(ss_adr); end if;
               ss_busy <= '1'; ss_left := 3 + to_integer(lfsr(2 downto 0));
            end if;
         end if;
         spu_regs_s <= regs; spu_ss_s <= ss; spu_ram_s <= spuram;
         if at_cpu_edge then
            if SAVE_AT > 0 and cycle_count = SAVE_AT then
               assert want_save = '0' and want_load = '0' report "save request while busy" severity failure;
               want_save <= '1'; trap <= '1';
            end if;
            if LOAD_AT > 0 and cycle_count = LOAD_AT then
               assert want_save = '0' and want_load = '0' report "load request while busy" severity failure;
               want_load <= '1'; trap <= '1';
            end if;
         end if;
      end if;
   end process;
   bus_exp1_dataRead <= exp1_q;
   bus_spu_dataRead <= spu_q;

   -- ---------------- GPU model ----------------
   bus_gpu_dataRead <= gpu_q;
   bus_gpu_stall <= gpu_stall;
   process (clk1x)
      variable vram : words(0 to VRAM_ROWS * 512 - 1);
      variable initialised : boolean := false;
      variable e1 : std_logic_vector(11 downto 0) := (others => '0');
      variable mask : std_logic_vector(1 downto 0) := "00";
      variable mode : std_logic_vector(7 downto 0) := (others => '0');
      variable dma : std_logic_vector(1 downto 0) := "00";
      variable disp_off, irq : std_logic := '0';
      variable tw, e3, e4, e5, gpuread : std_logic_vector(31 downto 0) := (others => '0');
      variable vrange : std_logic_vector(18 downto 0) := (others => '0');
      variable hrange : std_logic_vector(23 downto 0) := (others => '0');
      variable vdrange : std_logic_vector(19 downto 0) := (others => '0');
      variable cmd : std_logic_vector(7 downto 0) := (others => '0');
      variable params, pixels_in, pixels_out, k : natural := 0;
      variable rx, ry, rw, rh : natural := 0;
      variable value, d, stat : std_logic_vector(31 downto 0);
      variable pending : boolean := false;
      variable wait_left : natural := 0;
      variable half : std_logic_vector(15 downto 0);
      procedure pixel_at(n : natural; variable index : out natural; variable high : out boolean) is
         variable x, y : natural;
      begin
         x := (rx + n mod rw) mod 1024; y := (ry + n / rw) mod VRAM_ROWS;
         index := y * 512 + x / 2; high := x mod 2 = 1;
      end procedure;
      procedure put(v : std_logic_vector(15 downto 0)) is
         variable index : natural; variable high : boolean;
      begin
         pixel_at(k, index, high);
         if high then vram(index)(31 downto 16) := v; else vram(index)(15 downto 0) := v; end if;
         k := k + 1;
      end procedure;
      procedure get(variable v : out std_logic_vector(15 downto 0)) is
         variable index : natural; variable high : boolean;
      begin
         pixel_at(k, index, high);
         k := k + 1;
         if high then v := vram(index)(31 downto 16); else v := vram(index)(15 downto 0); end if;
      end procedure;
      procedure reset_gpu is
      begin
         e1 := (others => '0'); mask := "00"; mode := (others => '0'); dma := "00"; disp_off := '1'; irq := '0';
         tw := (others => '0'); e3 := (others => '0'); e4 := (others => '0'); e5 := (others => '0');
         vrange := (others => '0'); hrange := (others => '0'); vdrange := (others => '0');
         params := 0; pixels_in := 0; pixels_out := 0;
      end procedure;
   begin
      if rising_edge(clk1x) then
         if not initialised then
            for i in vram'range loop vram(i) := std_logic_vector(to_unsigned((i * 7919 + SEED * 104729) mod 2**30, 32)); end loop;
            initialised := true;
         end if;
         gpu_q <= (others => '0');
         if pending then
            if wait_left <= 1 then gpu_q <= value; gpu_stall <= '0'; pending := false;
            else wait_left := wait_left - 1; end if;
         end if;
         if reset = '0' and mux_bus_gpu_read = '1' then
            assert not pending report "GPU read while a read waits" severity failure;
            if mux_bus_gpu_addr(2) = '1' then
               value := stat;
            elsif pixels_out > 0 then
               get(half); value(15 downto 0) := half; get(half); value(31 downto 16) := half; pixels_out := pixels_out - 1;
            else
               value := gpuread;
            end if;
            wait_left := to_integer(lfsr(1 downto 0));
            if wait_left = 0 then gpu_q <= value; gpu_stall <= '0';
            else gpu_stall <= '1'; pending := true; end if;
         end if;
         if reset = '0' and mux_bus_gpu_write = '1' then
            d := mux_bus_gpu_dataWrite;
            if mux_bus_gpu_addr(2) = '1' then                 -- GP1
               case to_integer(unsigned(d(29 downto 24))) is
                  when 16#00# => reset_gpu;
                  when 16#01# => params := 0; pixels_in := 0;
                  when 16#02# => irq := '0';
                  when 16#03# => disp_off := d(0);
                  when 16#04# => dma := d(1 downto 0);
                  when 16#05# => vrange := d(18 downto 1) & '0';
                  when 16#06# => hrange := d(23 downto 0);
                  when 16#07# => vdrange := d(19 downto 0);
                  when 16#08# => mode := d(7 downto 0);
                  when 16#10# to 16#1F# =>
                     case to_integer(unsigned(d(2 downto 0))) is
                        when 2 => gpuread := tw;
                        when 3 => gpuread := e3;
                        when 4 => gpuread := e4;
                        when 5 => gpuread := e5;
                        when others => null;
                     end case;
                  when others => report "GPU model: GP1 " & to_hstring(d) severity failure;
               end case;
            elsif pixels_in > 0 then                         -- GP0 data
               put(d(15 downto 0)); put(d(31 downto 16)); pixels_in := pixels_in - 1;
            elsif params > 0 then
               if params = 2 then rx := to_integer(unsigned(d(9 downto 0))); ry := to_integer(unsigned(d(24 downto 16)));
               else
                  rw := to_integer(unsigned(d(10 downto 0))); rh := to_integer(unsigned(d(25 downto 16)));
                  if rw = 0 then rw := 1024; end if;
                  if rh = 0 then rh := 512; end if;
                  k := 0;
                  if cmd = x"A0" then pixels_in := (rw * rh + 1) / 2; else pixels_out := (rw * rh + 1) / 2; end if;
               end if;
               params := params - 1;
            else
               cmd := d(31 downto 24);
               case cmd is
                  when x"00" | x"01" => null;
                  when x"1F" => irq := '1';
                  when x"A0" | x"C0" => params := 2;
                  when x"E1" => e1 := d(11 downto 0);
                  when x"E2" => tw := x"000" & d(19 downto 0);
                  when x"E3" => e3 := x"000" & '0' & d(18 downto 0);
                  when x"E4" => e4 := x"000" & '0' & d(18 downto 0);
                  when x"E5" => e5 := x"00" & "00" & d(21 downto 0);
                  when x"E6" => mask := d(1 downto 0);
                  when others => report "GPU model: GP0 " & to_hstring(d) severity failure;
               end case;
            end if;
         end if;
         stat := (others => '0');
         stat(10 downto 0) := e1(10 downto 0); stat(15) := e1(11); stat(12 downto 11) := mask(1) & mask(0);
         stat(18 downto 17) := mode(1 downto 0); stat(22 downto 19) := mode(5 downto 2);
         stat(16) := mode(6); stat(14) := mode(7);
         stat(23) := disp_off; stat(24) := irq; stat(30 downto 29) := dma; stat(28) := '1';
         if params = 0 and pixels_in = 0 and not (GPU_HOLD > 0 and cycle_count >= SAVE_AT and cycle_count < SAVE_AT + GPU_HOLD) then
            stat(26) := '1';
         end if;
         if pixels_out > 0 then stat(27) := '1'; end if;
         gpu_stat_s <= stat; gpu_tw <= tw; gpu_e3 <= e3; gpu_e4 <= e4; gpu_e5 <= e5;
         gpu_ranges <= vdrange & hrange & vrange;
         gpu_vram <= vram;
      end if;
   end process;

   -- ---------------- SDRAM model (tb_memorymux_fifo_cpu.vhd) ----------------
   process (clk3x)
      variable mem : words(0 to 524287) := load("ram.hex", 524288, true);
      variable s1 : positive := 77 + SEED;
      variable s2 : positive := 9001 + SEED;
      variable r : real;
      variable pending, fill, finishing : boolean := false;
      variable delay, word_index, start_word, index : natural := 0;
      variable adr : std_logic_vector(24 downto 0);
      variable rnw : std_logic;
      variable be : std_logic_vector(3 downto 0);
      variable wdata, value : std_logic_vector(31 downto 0);
      variable at_cpu_edge : boolean;
      file dump : text;
      variable row : line;

      impure function fetch(a : std_logic_vector(24 downto 0)) return std_logic_vector is
      begin
         if a(24 downto 23) = "00" then
            return mem(to_integer(unsigned(a(20 downto 2))));
         elsif a(24 downto 23) = "01" and unsigned(a(18 downto 9)) = 0 then
            return rom(to_integer(unsigned(a(8 downto 2))));
         else
            return x"00000000";
         end if;
      end function;
   begin
      if rising_edge(clk3x) then
         at_cpu_edge := clk1x = '1' and clk1x'last_event = 0 ns;
         cache_wr <= "0000";
         if at_cpu_edge then
            ram_cpu_done <= '0';
         end if;
         if finishing then
            ram_cpu_done <= '1'; pending := false; finishing := false;
         elsif pending and fill and delay = 0 and not at_cpu_edge then
            value := fetch(adr(24 downto 4) & std_logic_vector(to_unsigned(word_index, 2)) & "00");
            cache_data <= value;
            cache_addr <= adr(11 downto 4);
            cache_wr <= std_logic_vector(shift_left(to_unsigned(1, 4), word_index));
            if word_index = start_word then ram_data <= value; end if;
            if word_index = 3 then finishing := true; else word_index := word_index + 1; end if;
         end if;
         if at_cpu_edge and reset = '0' then
            if pending and not fill and not finishing then
               if delay > 0 then
                  delay := delay - 1;
               else
                  if rnw = '1' then
                     ram_data <= fetch(adr);
                  elsif adr(24 downto 23) = "00" then
                     index := to_integer(unsigned(adr(20 downto 2)));
                     for b in 0 to 3 loop
                        if be(b) = '1' then mem(index)(8*b+7 downto 8*b) := wdata(8*b+7 downto 8*b); end if;
                     end loop;
                  end if;
                  ram_cpu_done <= '1'; pending := false;
               end if;
            elsif pending and fill and delay > 0 then
               delay := delay - 1;
            end if;
            if mux_ram_ena = '1' then
               assert not pending report "memorymux issued ram_ena while busy" severity failure;
               uniform(s1, s2, r);
               adr := mux_ram_Adr; rnw := mux_ram_rnw; be := mux_ram_be; wdata := mux_ram_dataWrite;
               pending := true; delay := natural(floor(r * 5.0)) mod 5;
               fill := mux_ram_cache = '1' and rnw = '1';
               start_word := to_integer(unsigned(adr(3 downto 2))); word_index := start_word;
               if rnw = '0' and unsigned(adr(24 downto 12)) = 3 then log_stores <= log_stores + 1; end if;
               if rnw = '0' and unsigned(adr) = 16#FF00# and wdata = x"600DF00D" and finished = '0' then
                  finished <= '1';
                  file_open(dump, "dump.hex", write_mode);
                  for k in 0 to DUMP_BYTES / 4 - 1 loop
                     hwrite(row, mem(k)); writeline(dump, row);
                  end loop;
                  for k in 0 to 6 loop
                     case k is
                        when 0 => value := gpu_stat_s;
                        when 1 => value := gpu_tw;
                        when 2 => value := gpu_e3;
                        when 3 => value := gpu_e4;
                        when 4 => value := gpu_e5;
                        when 5 => value := gpu_ranges(31 downto 0);
                        when others => value := '0' & gpu_ranges(62 downto 32);
                     end case;
                     hwrite(row, value); writeline(dump, row);
                  end loop;
                  for k in gpu_vram'range loop
                     hwrite(row, gpu_vram(k)); writeline(dump, row);
                  end loop;
                  for k in 0 to 127 loop hwrite(row, spu_regs_s(2 * k + 1) & spu_regs_s(2 * k)); writeline(dump, row); end loop;
                  for k in 0 to 511 loop hwrite(row, spu_ss_s(k)); writeline(dump, row); end loop;
                  for k in 0 to SPU_PAGES * 512 - 1 loop hwrite(row, spu_ram_s(2 * k + 1) & spu_ram_s(2 * k)); writeline(dump, row); end loop;
                  file_close(dump);
                  report "STATS save trap seed=" & integer'image(SEED) & " cycles=" & integer'image(cycle_count) &
                     " retired=" & integer'image(retired) & " log_stores=" & integer'image(log_stores) &
                     " saves=" & integer'image(saves_done) & " saves_failed=" & integer'image(saves_failed) &
                     " loads=" & integer'image(loads_done) &
                     " loads_failed=" & integer'image(loads_failed) & " handler_fetches=" & integer'image(handler_fetches) &
                     " retries=" & integer'image(retries) & " spu_writes=" & integer'image(spu_guest_writes);
                  assert trap = '0' and want_save = '0' and want_load = '0' report "request still open at the finish" severity failure;
                  assert spu_hold = '0' report "SPU still held at the finish" severity failure;
                  report "PASS save trap run";
                  finish;
               end if;
            end if;
         end if;
      end if;
   end process;

end architecture;
