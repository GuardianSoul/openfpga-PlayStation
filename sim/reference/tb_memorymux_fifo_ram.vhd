-- Lockstep: unmodified MiSTer memorymux (work, MLAB write FIFO) against the
-- memorymux-fifo-ram copy (library cand, M10K write FIFO). Both get the same
-- inputs every cycle; the inputs are produced by models fed from the
-- reference outputs: a CPU memory-port model following cpu.vhd's request
-- protocol (mem_request gated by busy/mem_done, stores until mem_fifofull),
-- an SDRAM model with random latency, a DMA pause model following psx_top
-- (pauseNext = cpuPaused or dmaRequest and isIdle), random bus data, GPU
-- stalls, CE pauses and resets. Every output port is compared at every
-- clk2x edge (both clk1x phases); writeFifo_Empty/NearFull are compared at
-- every clk1x edge and writeFifo_Dout whenever the FIFO is not empty.
-- Port declarations, instances and the output comparison are generated by
-- scripts/run_memorymux_fifo_ram.py.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;
use std.env.all;
library cand;

entity tb_memorymux_fifo_ram is
   generic
   (
      SEED       : positive := 1;
      CYCLES     : natural  := 200000;
      TURBO_ON   : boolean  := false;
      AGGRESSIVE : boolean  := false;
      LABEL_TEXT : string   := "BYPASS";
      -- false: only the memorymux ports are compared (negative controls must
      -- then be caught by externally visible behaviour alone)
      CHECK_INTERNAL : boolean := true
   );
end entity;

architecture test of tb_memorymux_fifo_ram is
   -- GENERATED_DECLARATIONS

   signal want, want_rnw, want_isdata, want_iscache : std_logic := '0';
   signal want_addr   : unsigned(31 downto 0) := (others => '0');
   signal want_instr  : unsigned(31 downto 0) := (others => '0');
   signal want_size   : unsigned(1 downto 0)  := "10";
   signal want_mask   : std_logic_vector(3 downto 0) := "1111";
   signal want_data   : std_logic_vector(31 downto 0) := (others => '0');
   signal want_tags   : std_logic_vector(3 downto 0) := "0000";
   signal busy        : std_logic := '0';
   signal cpuPaused   : std_logic := '0';
   signal dmaRequest  : std_logic := '0';

   signal cycle_count, stores, loads, fetches, fifo_writes, fifo_reads : natural := 0;
   signal nearfull_cycles, fullwrite, empty_writes, wr_rd_same, resets, dma_bursts : natural := 0;
   signal ce_pauses, dout_checks, max_count, store_while_full : natural := 0;
begin

   clk1x <= not clk1x after 15 ns;
   clk2x <= not clk2x after 7500 ps;

   -- CPU memory port (cpu.vhd: mem_request is held off while a read is
   -- outstanding unless mem_done arrives in the same cycle).
   mem_in_request      <= want and ((not busy) or ref_mem_done);
   mem_in_rnw          <= want_rnw;
   mem_in_isData       <= want_isdata;
   mem_in_isCache      <= want_iscache;
   mem_in_oldtagvalids <= want_tags;
   mem_in_addressInstr <= want_instr;
   mem_in_addressData  <= want_addr;
   mem_in_reqsize      <= want_size;
   mem_in_writeMask    <= want_mask;
   mem_in_dataWrite    <= want_data;

   pauseNext <= cpuPaused or (dmaRequest and ref_isIdle);

   process (clk1x)
      variable s1 : positive := SEED;
      variable s2 : positive := 7919 + SEED * 31;
      variable r  : real;
      variable reset_left, pause_left, dma_left, idle_left : natural := 0;
      variable accepted : boolean;
      variable kind, region, size, offset : natural;
      variable address : unsigned(31 downto 0);
      variable configured : boolean := false;

      impure function rnd return real is
      begin
         uniform(s1, s2, r);
         return r;
      end function;

      impure function rint(n : positive) return natural is
      begin
         return natural(floor(rnd * real(n))) mod n;
      end function;

      impure function rword return std_logic_vector is
      begin
         return std_logic_vector(to_unsigned(rint(65536), 16)) & std_logic_vector(to_unsigned(rint(65536), 16));
      end function;

      impure function rbits(n : positive) return std_logic_vector is
         variable w : std_logic_vector(31 downto 0);
      begin
         w := rword;
         return w(n - 1 downto 0);
      end function;

      impure function rbit return std_logic is
      begin
         if rint(2) = 0 then return '0'; else return '1'; end if;
      end function;

      impure function data_address(load : boolean) return unsigned is
         variable a : unsigned(31 downto 0);
         variable pick : natural;
      begin
         pick := rint(100);
         if pick < 55 then      -- main RAM, a few DRAM pages, three segments
            a := to_unsigned(rint(8) * 1024 + rint(256) * 4, 32);
            case rint(3) is
               when 0 => null;
               when 1 => a := a or x"80000000";
               when others => a := a or x"A0000000";
            end case;
         elsif pick < 70 then   -- internal I/O (memc, pad, sio, irq, dma, timers, gpu, mdec)
            if rint(2) = 0 then a := x"1F801000" + to_unsigned(rint(512) * 4, 32);
            else a := x"1F801810" + to_unsigned(rint(16) * 4, 32); end if;
         elsif pick < 75 then a := x"1F801800" + to_unsigned(rint(4), 32);          -- CD
         elsif pick < 85 then a := x"1F801C00" + to_unsigned(rint(256) * 4, 32);    -- SPU
         elsif pick < 88 then a := x"1F000000" + to_unsigned(rint(64) * 4, 32);     -- EXP1
         elsif pick < 92 then a := x"1F802000" + to_unsigned(rint(64) * 4, 32);     -- EXP2
         elsif pick < 94 then a := x"1FA00000";                                     -- EXP3
         else
            if load then a := x"BFC00000" + to_unsigned(rint(4096) * 4, 32);        -- BIOS
            else a := to_unsigned(rint(256) * 4, 32) or x"A0000000"; end if;
         end if;
         return a;
      end function;
   begin
      if rising_edge(clk1x) then
         cycle_count <= cycle_count + 1;

         if not configured then
            configured := true;
            TURBO       <= '1' when TURBO_ON else '0';
            fastboot    <= '1' when rint(2) = 0 else '0';
            PATCHSERIAL <= '1' when rint(2) = 0 else '0';
            region_in   <= std_logic_vector(to_unsigned(rint(3), 2));
            bios_memctrl <= to_unsigned(rint(4) + 16 * rint(4) + 256 * rint(64), 14);
            ex1_memctrl  <= to_unsigned(rint(4) + 16 * rint(4) + 256 * rint(64), 14);
            cd_memctrl   <= to_unsigned(rint(4) + 16 * rint(4) + 256 * rint(64), 14);
            spu_memctrl  <= to_unsigned(rint(4) + 16 * rint(4) + 256 * rint(64), 14);
            ex2_memctrl  <= to_unsigned(rint(4) + 16 * rint(4) + 256 * rint(64), 14);
            ex3_memctrl  <= to_unsigned(rint(4) + 16 * rint(4) + 256 * rint(64), 14);
            com0_delay   <= to_unsigned(rint(4), 4);
            com1_delay   <= to_unsigned(rint(4), 4);
            com2_delay   <= to_unsigned(rint(4), 4);
            com3_delay   <= to_unsigned(rint(4), 4);
         end if;

         -- Bus read data changes every cycle, so any timing slip shows.
         bus_exp1_dataRead  <= rbits(8);
         bus_memc_dataRead  <= rword;
         bus_pad_dataRead   <= rword;
         bus_sio_dataRead   <= rword;
         bus_memc2_dataRead <= rword;
         bus_irq_dataRead   <= rword;
         bus_dma_dataRead   <= rword;
         bus_tmr_dataRead   <= rword;
         bus_cd_dataRead    <= rbits(8);
         bus_gpu_dataRead   <= rword;
         bus_mdec_dataRead  <= rword;
         bus_spu_dataRead   <= rbits(16);
         bus_exp2_dataRead  <= rbits(8);
         bus_exp3_dataRead  <= rbits(16);
         bus_gpu_stall      <= '1' when rint(5) = 0 else '0';

         -- Resets (rare, 1-6 cycles).
         if reset_left > 0 then
            reset_left := reset_left - 1;
            if reset_left = 0 then reset <= '0'; end if;
         elsif cycle_count > 20 and rint(25000) = 0 then
            reset <= '1'; reset_left := 1 + rint(6); resets <= resets + 1;
         elsif cycle_count = 2 then
            reset <= '1'; reset_left := 4;
         end if;

         -- CE pauses (rare). psx_top only stops CE while memorymux is idle
         -- and the CPU has nothing outstanding (stallNext = 0); mem_done
         -- is not CE-gated, so pausing over a pending read would lose it.
         if pause_left > 0 then
            pause_left := pause_left - 1;
            if pause_left = 0 then ce <= '1'; end if;
         elsif rint(100) = 0 and ref_isIdle = '1' and busy = '0' and mem_in_request = '0' then
            ce <= '0'; pause_left := 1 + rint(4); ce_pauses <= ce_pauses + 1;
         else
            ce <= '1';
         end if;

         -- DMA: request, wait for memorymux idle, hold the CPU off a while.
         if cpuPaused = '1' then
            if dma_left > 0 then dma_left := dma_left - 1; else cpuPaused <= '0'; end if;
         elsif dmaRequest = '1' then
            if ref_isIdle = '1' then
               cpuPaused <= '1'; dmaRequest <= '0'; dma_left := 1 + rint(40); dma_bursts <= dma_bursts + 1;
            end if;
         elsif rint(150) = 0 then
            dmaRequest <= '1';
         end if;

         -- CPU request model.
         if reset = '1' then
            busy <= '0'; want <= '0'; idle_left := 0;
         elsif ce = '1' then
            accepted := mem_in_request = '1';
            if ref_mem_done = '1' then busy <= '0'; end if;
            if accepted then
               busy <= mem_in_rnw;
               if want_isdata = '1' and want_rnw = '0' then
                  stores <= stores + 1;
                  if ref_mem_fifofull = '1' then store_while_full <= store_while_full + 1; end if;
               elsif want_isdata = '1' then loads <= loads + 1;
               else fetches <= fetches + 1; end if;
            end if;
            if accepted or want = '0' then
               want <= '0';
               -- Unused request fields carry junk, as CPU outputs do.
               want_addr <= unsigned(rword); want_instr <= unsigned(rword); want_data <= rword;
               want_mask <= rbits(4); want_size <= unsigned(rbits(2));
               want_tags <= rbits(4); want_iscache <= rbit;
               want_rnw <= rbit; want_isdata <= rbit;
               if idle_left > 0 then
                  idle_left := idle_left - 1;
               else
                  kind := rint(100);
                  if kind < 50 and (ref_mem_fifofull = '0' or (AGGRESSIVE and rint(3) = 0)) then
                     address := data_address(false);
                     size := rint(3);
                     want <= '1'; want_rnw <= '0'; want_isdata <= '1'; want_iscache <= '0';
                     want_data <= rword;
                     if size = 0 then
                        offset := rint(4); want_size <= "00";
                        want_mask <= std_logic_vector(shift_left(to_unsigned(1, 4), offset));
                     elsif size = 1 then
                        offset := 2 * rint(2); want_size <= "01";
                        want_mask <= std_logic_vector(shift_left(to_unsigned(3, 4), offset));
                     else
                        offset := 0; want_size <= "10"; want_mask <= "1111";
                     end if;
                     want_addr <= address(31 downto 2) & to_unsigned(offset, 2);
                  elsif kind < 50 then
                     null;  -- CPU stalled on mem_fifofull
                  elsif kind < 68 then
                     address := data_address(true);
                     want <= '1'; want_rnw <= '1'; want_isdata <= '1'; want_iscache <= '0';
                     size := rint(3);
                     want_size <= to_unsigned(size, 2);
                     if size = 0 then want_addr <= address(31 downto 2) & to_unsigned(rint(4), 2);
                     elsif size = 1 then want_addr <= address(31 downto 2) & to_unsigned(2 * rint(2), 2);
                     else want_addr <= address; end if;
                  elsif kind < 85 then
                     want <= '1'; want_rnw <= '1'; want_isdata <= '0';
                     if rint(12) = 0 then
                        want_instr <= x"BFC00000" + to_unsigned(rint(4096) * 4, 32); want_iscache <= '0';
                     else
                        want_instr <= x"80000000" + to_unsigned(rint(8) * 1024 + rint(256) * 4, 32);
                        want_iscache <= '1' when rint(2) = 0 else '0';
                     end if;
                  else
                     idle_left := rint(6);
                  end if;
               end if;
            end if;
         end if;
      end if;
   end process;

   -- SDRAM model: one access in flight, done 1..7 cycles after ram_ena.
   process (clk1x)
      type ram_t is array(0 to 4095) of std_logic_vector(31 downto 0);
      variable ram : ram_t := (others => (others => '0'));
      variable s1 : positive := 101 + SEED;
      variable s2 : positive := 33331 + SEED;
      variable r : real;
      variable pending : boolean := false;
      variable delay : natural := 0;
      variable p_rnw : std_logic;
      variable p_index : natural;
      variable p_be : std_logic_vector(3 downto 0);
      variable p_data : std_logic_vector(31 downto 0);
   begin
      if rising_edge(clk1x) then
         ram_done <= '0';
         if pending then
            if delay = 0 then
               if p_rnw = '1' then
                  ram_dataRead <= ram(p_index);
               else
                  for b in 0 to 3 loop
                     if p_be(b) = '1' then ram(p_index)(8*b+7 downto 8*b) := p_data(8*b+7 downto 8*b); end if;
                  end loop;
               end if;
               ram_done <= '1';
               pending := false;
            else
               delay := delay - 1;
            end if;
         end if;
         if ref_ram_ena = '1' then
            assert not pending report "memorymux issued ram_ena while busy" severity failure;
            uniform(s1, s2, r);
            pending := true; delay := natural(floor(r * 7.0)) mod 7;
            p_rnw := ref_ram_rnw; p_be := ref_ram_be; p_data := ref_ram_dataWrite;
            p_index := to_integer(unsigned(ref_ram_Adr(13 downto 2)) xor unsigned(ref_ram_Adr(24 downto 13)));
         end if;
      end if;
   end process;

   -- Write FIFO internals of both instances.
   process (clk1x)
      alias r_empty is << signal .tb_memorymux_fifo_ram.ref_mux.writeFifo_Empty : std_logic >>;
      alias c_empty is << signal .tb_memorymux_fifo_ram.cand_mux.writeFifo_Empty : std_logic >>;
      alias r_near  is << signal .tb_memorymux_fifo_ram.ref_mux.writeFifo_NearFull : std_logic >>;
      alias c_near  is << signal .tb_memorymux_fifo_ram.cand_mux.writeFifo_NearFull : std_logic >>;
      alias r_dout  is << signal .tb_memorymux_fifo_ram.ref_mux.writeFifo_Dout : std_logic_vector(69 downto 0) >>;
      alias c_dout  is << signal .tb_memorymux_fifo_ram.cand_mux.writeFifo_Dout : std_logic_vector(69 downto 0) >>;
      alias r_wr    is << signal .tb_memorymux_fifo_ram.ref_mux.writeFifo_Wr : std_logic >>;
      alias r_rd    is << signal .tb_memorymux_fifo_ram.ref_mux.writeFifo_Rd : std_logic >>;
      alias r_count is << signal .tb_memorymux_fifo_ram.ref_mux.iwritefifo.fifocnt : unsigned(2 downto 0) >>;
   begin
      if rising_edge(clk1x) then
         assert not CHECK_INTERNAL or (r_empty = c_empty and r_near = c_near)
            report "write FIFO Empty/NearFull mismatch" severity failure;
         if r_empty = '0' and CHECK_INTERNAL then
            assert r_dout = c_dout
               report "write FIFO Dout mismatch: ref=" & to_hstring(r_dout) & " cand=" & to_hstring(c_dout)
               severity failure;
            dout_checks <= dout_checks + 1;
         end if;
         if reset = '0' then
            if r_wr = '1' then
               fifo_writes <= fifo_writes + 1;
               if r_empty = '1' then empty_writes <= empty_writes + 1; end if;
               if r_rd = '1' then wr_rd_same <= wr_rd_same + 1; end if;
               if r_count = 7 then fullwrite <= fullwrite + 1; end if;
            end if;
            if r_rd = '1' then fifo_reads <= fifo_reads + 1; end if;
            if r_near = '1' then nearfull_cycles <= nearfull_cycles + 1; end if;
            if to_integer(r_count) > max_count then max_count <= to_integer(r_count); end if;
         end if;
      end if;
   end process;

   -- GENERATED_COMPARE

   process (clk1x)
   begin
      if rising_edge(clk1x) and cycle_count = CYCLES then
         report "STATS memorymux FIFO RAM " & LABEL_TEXT & " seed=" & integer'image(SEED) &
            " turbo=" & boolean'image(TURBO_ON) & " aggressive=" & boolean'image(AGGRESSIVE) &
            " cycles=" & integer'image(cycle_count) & " stores=" & integer'image(stores) &
            " loads=" & integer'image(loads) & " fetches=" & integer'image(fetches) &
            " fifo_writes=" & integer'image(fifo_writes) & " fifo_reads=" & integer'image(fifo_reads) &
            " writes_into_empty=" & integer'image(empty_writes) & " write_read_same_cycle=" & integer'image(wr_rd_same) &
            " nearfull_cycles=" & integer'image(nearfull_cycles) & " max_count=" & integer'image(max_count) &
            " writes_at_count7=" & integer'image(fullwrite) & " stores_while_fifofull=" & integer'image(store_while_full) &
            " dout_checks=" & integer'image(dout_checks) & " dma_bursts=" & integer'image(dma_bursts) &
            " ce_pauses=" & integer'image(ce_pauses) & " resets=" & integer'image(resets);
         assert fifo_writes > CYCLES / 100 and nearfull_cycles > 0 and max_count >= 4 and empty_writes > 0
            and wr_rd_same > 0 and dma_bursts > 0 and ce_pauses > 0
            report "memorymux FIFO coverage missing" severity failure;
         report "PASS memorymux FIFO RAM " & LABEL_TEXT & " seed=" & integer'image(SEED);
         finish;
      end if;
   end process;

end architecture;
