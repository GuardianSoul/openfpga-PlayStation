-- Lockstep: two complete MiSTer CPU + memorymux pairs. ref_cpu/ref_mux use
-- the unmodified memorymux (MLAB write FIFO); cand_cpu/cand_mux use the
-- memorymux-fifo-ram copy (library cand). Shared models are driven by the
-- reference pair: an SDRAM model (random latency, instruction-cache line
-- fills on clk3x, byte enables), a psx_top-style DMA pause (pauseNext =
-- cpuPaused or dmaRequest and isIdle), idle-only CE pauses and changing bus
-- read data. The CPU runs a generated cached program (rom.hex bootstrap,
-- ram.hex body) of store bursts, loads and ALU work against RAM and I/O,
-- ending with a marker store. Every CPU and memorymux output is compared at
-- every clk2x and clk3x edge, the FIFO's Empty/NearFull/Dout at clk1x.
-- Declarations, instances, comparison and bus stubs are generated by
-- scripts/run_memorymux_fifo_ram.py.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
use ieee.math_real.all;
use std.textio.all;
use std.env.all;
use work.pexport.all;
library cand;

entity tb_memorymux_fifo_cpu is
   generic
   (
      SEED       : positive := 1;
      LABEL_TEXT : string   := "cpu";
      MAX_CYCLES : natural  := 2000000;
      PROGRESS   : natural  := 0
   );
end entity;

architecture test of tb_memorymux_fifo_cpu is
   type words is array(natural range <>) of std_logic_vector(31 downto 0);
   impure function load(path : string; size : positive; sparse : boolean) return words is
      file data : text open read_mode is path;
      variable row : line;
      variable result : words(0 to size - 1) := (others => (others => '0'));
      variable address : std_logic_vector(31 downto 0);
      variable index : natural := 0;
   begin
      while not endfile(data) loop
         readline(data, row);
         if sparse then hread(row, address); index := to_integer(unsigned(address)) / 4; end if;
         assert index < size report "image exceeds memory" severity failure;
         hread(row, result(index)); index := index + 1;
      end loop;
      return result;
   end function;
   constant rom : words(0 to 127) := load("rom.hex", 128, false);

   signal clk1x, clk2x, clk3x : std_logic := '1';
   signal reset, ss_reset : std_logic := '1';
   signal ce : std_logic := '1';
   signal cpuPaused, dmaRequest, pause_next : std_logic := '0';
   signal ram_data : std_logic_vector(31 downto 0) := (others => '0');
   signal ram_cpu_done : std_logic := '0';
   signal cache_wr : std_logic_vector(3 downto 0) := "0000";
   signal cache_data : std_logic_vector(31 downto 0) := (others => '0');
   signal cache_addr : std_logic_vector(7 downto 0) := (others => '0');
   signal lfsr : unsigned(63 downto 0) := x"0123456789ABCDEF";
   signal memory_busy, finished : std_logic := '0';

   signal cycle_count, retired, stores, fifo_writes, nearfull_cycles, max_count : natural := 0;
   signal fills, dma_bursts, ce_pauses, dout_checks, ram_writes, ram_reads : natural := 0;

   -- GENERATED_DECLARATIONS
begin

   clk1x <= not clk1x after 15 ns;
   clk2x <= not clk2x after 7500 ps;
   clk3x <= not clk3x after 5 ns;

   pause_next <= cpuPaused or (dmaRequest and ref_mux_isIdle);

   -- GENERATED_INSTANCES

   process
   begin
      for edge in 1 to 4 loop wait until falling_edge(clk1x); end loop;
      ss_reset <= '0';
      for edge in 1 to 50 loop wait until falling_edge(clk1x); end loop;
      reset <= '0';
      wait;
   end process;

   -- CE pauses only while CPU and memory are idle (psx_top's pause rule),
   -- DMA pauses as in psx_top, changing bus data and stubs.
   process (clk1x)
      variable s1 : positive := SEED;
      variable s2 : positive := 4243 + SEED;
      variable r : real;
      variable pause_left, dma_left, finish_wait : natural := 0;
   begin
      if rising_edge(clk1x) then
         cycle_count <= cycle_count + 1;
         assert cycle_count < MAX_CYCLES report "CPU program did not finish" severity failure;
         lfsr <= lfsr(62 downto 0) & (lfsr(63) xor lfsr(62) xor lfsr(60) xor lfsr(59));
         -- GENERATED_STUBS
         uniform(s1, s2, r);
         if reset = '1' then
            ce <= '1'; cpuPaused <= '0'; dmaRequest <= '0';
         else
            if pause_left > 0 then
               pause_left := pause_left - 1;
               if pause_left = 0 then ce <= '1'; end if;
            elsif r < 0.01 and ref_cpu_stallNext = '0' and ref_mux_isIdle = '1' and ref_cpu_SS_idle = '1'
                  and memory_busy = '0' and dmaRequest = '0' and cpuPaused = '0' and ram_cpu_done = '0' then
               ce <= '0'; pause_left := 1 + natural(floor(r * 300.0)); ce_pauses <= ce_pauses + 1;
            end if;
            if cpuPaused = '1' then
               if dma_left > 0 then dma_left := dma_left - 1; else cpuPaused <= '0'; end if;
            elsif dmaRequest = '1' then
               if ref_mux_isIdle = '1' then
                  cpuPaused <= '1'; dmaRequest <= '0'; dma_left := 1 + natural(floor(r * 6000.0)) mod 60;
                  dma_bursts <= dma_bursts + 1;
               end if;
            elsif r > 0.995 then
               dmaRequest <= '1';
            end if;
         end if;
         if PROGRESS > 0 and cycle_count mod PROGRESS = 0 then
            report "progress cycles=" & integer'image(cycle_count) & " retired=" & integer'image(retired) &
               " stores=" & integer'image(stores) & " pc=" & to_hstring(ref_cpu_cpu_export.pc);
         end if;
         if finished = '1' then
            finish_wait := finish_wait + 1;
            if finish_wait = 20 then
               report "STATS memorymux FIFO RAM " & LABEL_TEXT & " seed=" & integer'image(SEED) &
                  " cycles=" & integer'image(cycle_count) & " retired=" & integer'image(retired) &
                  " stores=" & integer'image(stores) & " fifo_writes=" & integer'image(fifo_writes) &
                  " nearfull_cycles=" & integer'image(nearfull_cycles) & " max_count=" & integer'image(max_count) &
                  " ram_writes=" & integer'image(ram_writes) & " ram_reads=" & integer'image(ram_reads) &
                  " line_fills=" & integer'image(fills) & " dma_bursts=" & integer'image(dma_bursts) &
                  " ce_pauses=" & integer'image(ce_pauses) & " dout_checks=" & integer'image(dout_checks);
               assert nearfull_cycles > 0 and max_count >= 4 and fifo_writes > 1000 and dma_bursts > 0 and fills > 0
                  report "memorymux FIFO CPU coverage missing" severity failure;
               report "PASS memorymux FIFO RAM " & LABEL_TEXT & " seed=" & integer'image(SEED);
               finish;
            end if;
         end if;
      end if;
   end process;

   -- SDRAM model on clk3x: one access at a time; data reads/writes complete
   -- 1..5 clk1x cycles after ram_ena; cached fetches write the line from the
   -- requested word to word 3 into the CPU cache on clk3x, then complete.
   process (clk3x)
      variable mem : words(0 to 524287) := load("ram.hex", 524288, true);
      variable s1 : positive := 77 + SEED;
      variable s2 : positive := 9001 + SEED;
      variable r : real;
      variable pending, fill, finishing : boolean := false;
      variable delay, word_index, start_word, index : natural := 0;
      variable adr : std_logic_vector(24 downto 0);
      variable rnw : std_logic;
      variable be : std_logic_vector(3 downto 0);
      variable wdata, value : std_logic_vector(31 downto 0);
      variable at_cpu_edge : boolean;

      impure function fetch(a : std_logic_vector(24 downto 0)) return std_logic_vector is
      begin
         if a(24 downto 23) = "00" then
            return mem(to_integer(unsigned(a(20 downto 2))));
         elsif a(24 downto 23) = "01" and unsigned(a(18 downto 9)) = 0 then
            return rom(to_integer(unsigned(a(8 downto 2))));
         else
            return x"00000000";
         end if;
      end function;
   begin
      if rising_edge(clk3x) then
         at_cpu_edge := clk1x = '1' and clk1x'last_event = 0 ns;
         cache_wr <= "0000";
         if at_cpu_edge then
            ram_cpu_done <= '0';
         end if;
         if finishing then
            ram_cpu_done <= '1'; pending := false; finishing := false; memory_busy <= '0';
         elsif pending and fill and delay = 0 and not at_cpu_edge then
            value := fetch(adr(24 downto 4) & std_logic_vector(to_unsigned(word_index, 2)) & "00");
            cache_data <= value;
            cache_addr <= adr(11 downto 4);
            cache_wr <= std_logic_vector(shift_left(to_unsigned(1, 4), word_index));
            if word_index = start_word then ram_data <= value; end if;
            if word_index = 3 then finishing := true; else word_index := word_index + 1; end if;
         end if;
         if at_cpu_edge and reset = '0' then
            if pending and not fill and not finishing then
               if delay > 0 then
                  delay := delay - 1;
               else
                  if rnw = '1' then
                     ram_data <= fetch(adr);
                  elsif adr(24 downto 23) = "00" then
                     index := to_integer(unsigned(adr(20 downto 2)));
                     for b in 0 to 3 loop
                        if be(b) = '1' then mem(index)(8*b+7 downto 8*b) := wdata(8*b+7 downto 8*b); end if;
                     end loop;
                  end if;
                  ram_cpu_done <= '1'; pending := false; memory_busy <= '0';
               end if;
            elsif pending and fill and delay > 0 then
               delay := delay - 1;
            end if;
            if ref_mux_ram_ena = '1' then
               assert not pending report "memorymux issued ram_ena while busy" severity failure;
               uniform(s1, s2, r);
               adr := ref_mux_ram_Adr; rnw := ref_mux_ram_rnw; be := ref_mux_ram_be; wdata := ref_mux_ram_dataWrite;
               pending := true; memory_busy <= '1'; delay := natural(floor(r * 5.0)) mod 5;
               fill := ref_mux_ram_cache = '1' and rnw = '1';
               start_word := to_integer(unsigned(adr(3 downto 2))); word_index := start_word;
               if fill then fills <= fills + 1; elsif rnw = '1' then ram_reads <= ram_reads + 1;
               else
                  ram_writes <= ram_writes + 1;
                  if unsigned(adr) = 16#FF00# and wdata = x"600DF00D" then finished <= '1'; end if;
               end if;
            end if;
         end if;
      end if;
   end process;

   process (clk1x)
      alias r_empty is << signal .tb_memorymux_fifo_cpu.ref_mux.writeFifo_Empty : std_logic >>;
      alias c_empty is << signal .tb_memorymux_fifo_cpu.cand_mux.writeFifo_Empty : std_logic >>;
      alias r_near  is << signal .tb_memorymux_fifo_cpu.ref_mux.writeFifo_NearFull : std_logic >>;
      alias c_near  is << signal .tb_memorymux_fifo_cpu.cand_mux.writeFifo_NearFull : std_logic >>;
      alias r_dout  is << signal .tb_memorymux_fifo_cpu.ref_mux.writeFifo_Dout : std_logic_vector(69 downto 0) >>;
      alias c_dout  is << signal .tb_memorymux_fifo_cpu.cand_mux.writeFifo_Dout : std_logic_vector(69 downto 0) >>;
      alias r_wr    is << signal .tb_memorymux_fifo_cpu.ref_mux.writeFifo_Wr : std_logic >>;
      alias r_count is << signal .tb_memorymux_fifo_cpu.ref_mux.iwritefifo.fifocnt : unsigned(2 downto 0) >>;
   begin
      if rising_edge(clk1x) then
         assert r_empty = c_empty and r_near = c_near report "write FIFO Empty/NearFull mismatch" severity failure;
         if r_empty = '0' then
            assert r_dout = c_dout report "write FIFO Dout mismatch" severity failure;
            dout_checks <= dout_checks + 1;
         end if;
         if reset = '0' then
            if r_wr = '1' then fifo_writes <= fifo_writes + 1; end if;
            if r_near = '1' then nearfull_cycles <= nearfull_cycles + 1; end if;
            if to_integer(r_count) > max_count then max_count <= to_integer(r_count); end if;
            if ce = '1' and ref_cpu_cpu_done = '1' then
               retired <= retired + 1;
               assert ref_cpu_cpu_export.pc /= x"80000080" report "program took an exception" severity failure;
            end if;
            if ce = '1' and ref_cpu_mem_request = '1' and ref_cpu_mem_rnw = '0' then stores <= stores + 1; end if;
         end if;
      end if;
   end process;

end architecture;
