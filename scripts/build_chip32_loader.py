#!/usr/bin/env python3
"""Assemble the APF Chip32 BIOS check loader (support/chip32/psx_bios_check.asm).

The official Chip32 assembler is bass (ARM9/bass, devel branch) with
Analogue's open-fpga/bass-chip32 architecture table. When bass is not on
PATH or under build/tools/bass-chip32, this clones both at the pinned
commits below and builds bass there. The program, followed by its generated
slot constants and strings, is assembled in a fresh build directory.
"""
import argparse
import json
import os
import re
from pathlib import Path
import shutil
import subprocess

from tool_paths import ROOT

BASS_REPO, BASS_COMMIT = 'https://github.com/ARM9/bass', '828ad2c11bddac45c7daeba9293a5265f2994bd5'
ARCH_REPO, ARCH_COMMIT = 'https://github.com/open-fpga/bass-chip32', '9e4a919d1ff39b217b75e090e996148654d3f9d7'
TOOLS = ROOT/'build/tools/bass-chip32'
SOURCE = ROOT/'support/chip32/psx_bios_check.asm'


def checkout(repo, commit, path):
    if not (path/'.git').is_dir():
        subprocess.run(['git', 'clone', '-q', repo, str(path)], check=True)
    if subprocess.run(['git', '-C', str(path), 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip() != commit:
        subprocess.run(['git', '-C', str(path), 'fetch', '-q', 'origin', commit], check=True)
        subprocess.run(['git', '-C', str(path), 'checkout', '-q', commit], check=True)


def find_bass():
    """bass next to an architectures/chip32.vm.arch, building it if needed."""
    found = shutil.which('bass')
    if found and (Path(found).parent/'architectures/chip32.vm.arch').is_file():
        return Path(found)
    built = TOOLS/'bass/bass/out/bass'
    if not built.is_file():
        checkout(BASS_REPO, BASS_COMMIT, TOOLS/'bass')
        # nall needs <stdexcept> with current GCC; it does not include it.
        subprocess.run(['make', '-C', str(TOOLS/'bass/bass'), f'-j{os.cpu_count() or 2}',
                        'compiler=g++ -include stdexcept'], check=True, stdout=subprocess.DEVNULL)
    arch = built.parent/'architectures/chip32.vm.arch'
    if not arch.is_file():
        checkout(ARCH_REPO, ARCH_COMMIT, TOOLS/'arch')
        arch.parent.mkdir(exist_ok=True)
        shutil.copyfile(TOOLS/'arch/architectures/chip32.vm.arch', arch)
    return built


# --bios-names (prepare --bios-names, package --bios-names): file names the
# core accepts, one slot each from 0x20, in the order the loader tries them:
# USA, Japan, Europe. The loader sets the CD region to the BIOS it loads.
# A plain build has one slot, the package's BIOS file name.
BIOS_NAMES = ('scph5501.bin', 'scph7001.bin', 'scph1001.bin', 'scph7501.bin', 'scph9001.bin', 'scph101.bin',
              'scph5500.bin', 'scph7000.bin', 'scph3500.bin', 'scph100.bin',
              'scph5502.bin', 'scph7002.bin', 'scph1002.bin', 'scph7502.bin', 'scph9002.bin', 'scph102.bin')
# Which names get a slot when APF's 32 run short (the cue-mount layout keeps
# 0.5.2's track slots 101-119): one per region first, then the rest.
BIOS_PRIORITY = ('scph5501.bin', 'scph5500.bin', 'scph5502.bin', 'scph1001.bin', 'scph7001.bin', 'scph7502.bin', 'scph7000.bin',
                 'scph7501.bin', 'scph1002.bin', 'scph9001.bin', 'scph9002.bin', 'scph7002.bin', 'scph101.bin', 'scph102.bin',
                 'scph3500.bin', 'scph100.bin')


# The disc image slot (package_pocket_early.py's "Disc image"); the loader reads
# the disc's region from it to prefer a BIOS of the same region.
DISC_SLOT = 101
CUE_SLOT = 100   # a game file's cue ("Disc (cue)"): its name gives the region


def name_region(name):
    """A BIOS file name's region by Sony's last digit (scph5501 USA, scph5500
    Japan, scph5502 Europe; 0 USA, 1 Japan, 2 Europe), 0xff for another name.
    The loader tries the disc's region's names first; the version line decides."""
    m = re.fullmatch(r'scph\d*([012])\.bin', name.lower())
    return {'1': 0, '0': 1, '2': 2}[m.group(1)] if m else 0xff


def config_text(slots, memcard_slot, platform, table=(), send_complete=False):
    return '\n'.join([
        '// Generated by scripts/build_chip32_loader.py',
        f'constant memcard_slot = {memcard_slot:#x}',
        f'constant send_complete = {int(send_complete)}',
        f'constant disc_slot = {DISC_SLOT if DISC_SLOT in table else 0xffff:#x}',
        f'constant cue_slot = {CUE_SLOT if CUE_SLOT in table else 0xffff:#x}',
        'bios_slots:',
        '                dw ' + ', '.join(f'{slot:#x}' for slot, _ in slots) + ', 0',
        'bios_expect:',
        '                dw ' + ', '.join(f'{name_region(name):#x}' for _, name in slots),
        'table_slots:',
        '                dw ' + ''.join(f'{slot:#x}, ' for slot in table) + '0xffff',
        'msg_names:',
        f'                db "{slots[0][1]}",0',
        '',
    ])


def build(output, slots=((0x20, 'scph5501.bin'),), memcard_slot=0xffff, platform='playstation', table=(), send_complete=False):
    """Assemble into output (a .bin path); slots are (id, file name) in the
    order the loader tries them, table the data.json slot IDs in order (the
    core's ID/size table). Returns output."""
    output = Path(output).resolve()
    work = output.parent/(output.stem+'-src')
    if work.exists(): shutil.rmtree(work)
    work.mkdir(parents=True)
    # The tables follow the program: it starts at the reset vectors.
    (work/'loader.asm').write_text('architecture chip32.vm\n'
        f'output "{output.name}", create\n' + SOURCE.read_text()
        + config_text(list(slots), memcard_slot, platform, table, send_complete))
    if output.exists(): output.unlink()
    bass = find_bass()
    result = subprocess.run([str(bass), '-strict', 'loader.asm'], cwd=work, capture_output=True, text=True)
    if result.returncode or not (work/output.name).is_file():
        raise SystemExit(f'bass failed:\n{result.stdout}{result.stderr}')
    data = (work/output.name).read_bytes()
    if len(data) > 0x1c00: raise SystemExit(f'Loader is {len(data)} bytes; it must stay below its 0x1c00 buffer')
    output.write_bytes(data)
    return output


def apply(core, platform, names=False, send_complete=False):
    """Give a packaged core folder the BIOS check: chip32.bin, core.json
    chip32_vm, and optional BIOS slots so the loader's message is shown
    instead of the Pocket's own missing-file error. Slots come from its
    data.json: the BIOS (address 0, exactly 512 KiB) and a nonvolatile card.
    names (needs a prepare --bios-names bitstream) appends one slot per
    BIOS_NAMES entry after the existing slots, keeping their table positions."""
    core = Path(core)
    meta, data = (json.loads((core/n).read_text()) for n in ('core.json', 'data.json'))
    slots = data['data']['data_slots']
    bios = [s for s in slots if s.get('size_exact') == 524288 and int(str(s.get('address', '-1')), 0) == 0 and not s.get('deferload')]
    if len(bios) != 1 or 'filename' not in bios[0]: raise SystemExit(f'{core}: expected one fixed-name BIOS slot')
    cards = [s for s in slots if s.get('nonvolatile') and int(str(s['id']), 0) != 1]   # not the boot log
    bios[0]['required'] = False
    first = int(str(bios[0]['id']), 0)
    order = [(first, bios[0]['filename'])]
    if names:
        if first != 0x20: raise SystemExit(f'{core}: --bios-names needs the BIOS in slot 0x20')
        extra = [n for n in BIOS_PRIORITY if n != bios[0]['filename']][:32 - len(slots)]
        if len(extra) < 3: raise SystemExit(f'{core}: {len(slots)} slots leave room for only {len(extra)} other BIOS names')
        extra.sort(key=BIOS_NAMES.index)
        for k, name in enumerate(extra, 1):
            slots.append(dict(bios[0], name=f'BIOS {name[:-4]}', id=f'{0x20+k:#04x}', filename=name))
            order.append((0x20+k, name))
        order.sort(key=lambda o: BIOS_NAMES.index(o[1]) if o[1] in BIOS_NAMES else -1)
    build(core/'chip32.bin', order, int(str(cards[0]['id']), 0) if cards else 0xffff, platform,
          [int(str(s['id']), 0) for s in slots], send_complete)
    meta['core']['framework']['chip32_vm'] = 'chip32.bin'
    for name, value in (('core.json', meta), ('data.json', data)):
        (core/name).write_text(json.dumps(value, indent=2)+'\n')
    shutil.rmtree(core/'chip32-src', ignore_errors=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'build/chip32/psx_bios_check.bin')
    parser.add_argument('--memcard-slot', type=lambda v: int(v, 0), default=0xffff, help='Nonvolatile card slot to load if present (0xffff: none)')
    parser.add_argument('--names', action='store_true', help='With --core: also accept BIOS_NAMES (needs a prepare --bios-names bitstream)')
    parser.add_argument('--send-complete', action='store_true', help='Also send the core command 0x0082 (all slots complete) before starting it')
    parser.add_argument('--platform', default='playstation')
    parser.add_argument('--core', type=Path, help='Add the BIOS check to this packaged core folder instead (slots from its data.json)')
    args = parser.parse_args()
    if args.core: return apply(args.core, args.platform, args.names, args.send_complete)
    print(build(args.output, memcard_slot=args.memcard_slot, platform=args.platform))


if __name__ == '__main__': main()
