def apply_sdram(manifest,directory,contract):
    directory=Path(directory).resolve();contract=Path(contract).resolve()
    report=json.loads(contract.read_text())
    if not report.get('passed') or not report.get('source_identity_verified') or \
        [r['name'] for r in report['runs']]!=['nominal','slow-source'] or \
        [f['name'] for f in report['faults']]!=['wrong-tag','early-idle'] or \
        not all(r['passed'] and r['exit_code']==0 for r in report['runs']) or \
        not all(f['passed'] and f['exit_code']!=0 for f in report['faults']):
        raise ValueError('Complete shared SDRAM traffic/drain proof required')
    if any(digest(Path(p))!=sha for p,sha in report['source_sha256'].items()):
        raise ValueError('Shared SDRAM proof source changed')
    out=directory/'sdram-only';out.mkdir()
    phy=prepare_phy(out/'phy');replacements={}
    for name in ('psx_top.vhd','psx_mister_psx_top_resource.vhd','memorymux.vhd'):
        candidates=[s for s in manifest['sources'] if Path(s['path']).name==name]
        if len(candidates)!=1:raise ValueError('Expected exactly one '+name)
        old=candidates[0];text=Path(old['path']).read_text()
        if name!='memorymux.vhd':
            text,n=re.subn(r'(isPaused\s*:\s*out std_logic;)',r'\1\n      memory_service_ce : out std_logic;',text)
            if n!=1:raise ValueError('Core observation port anchor changed')
            if name=='psx_top.vhd':
                text=replace_once(text,'   isPaused <= pausing;',
                    '   isPaused <= pausing;\n   memory_service_ce <= ce or savestate_busy;')
            else:
                text,n=re.subn(r'(isPaused\s*=>\s*isPaused,)',r'\1\n        memory_service_ce => memory_service_ce,',text)
                if n!=1:raise ValueError('Core wrapper observation map changed')
        text=fenced_top(text,name)
        path=out/name;path.write_text(text);replacements[old['path']]=source(path)
    core=directory/'core_top.sv';text=core.read_text()
    start=text.index('    wire mem_protocol_error=0;');end=text.index('    wire video_locked;',start)
    cpu_begin=text.index('    wire cpu_locked;',start)
    cpu_end=text.index('    altera_pll #(.fractional_vco_multiplier("false")',cpu_begin)
    cpu=text[cpu_begin:cpu_end].replace('    wire ps_clk, ps_clk2;\n','')
    text=text[:start]+cpu+MEMORY+text[end:]
    text=replace_once(text,'.isPaused(isPaused)',
        '.isPaused(isPaused),.memory_service_ce(memory_service_ce),'+
        '.main_reset_request(main_reset_request),.main_reset_hold(main_reset_hold)')
    for die in range(2):
        text=text.replace('endmodule',f'''    assign cram{die}_a=0,cram{die}_dq=16'bz,cram{die}_clk=0,
        cram{die}_adv_n=1,cram{die}_cre=0,cram{die}_ce0_n=1,cram{die}_ce1_n=1,
        cram{die}_oe_n=1,cram{die}_we_n=1,cram{die}_ub_n=1,cram{die}_lb_n=1;
endmodule''',1)
    core.write_text(text)
    sources=[replacements.get(s['path'],s) for s in manifest['sources']]
    sources += [phy,*[source(ROOT/'rtl/pocket'/name) for name in
        ('psx_sdram_shared.sv','psx_spu_sdram_adapter.sv','psx_mister_main_adapter.sv',
         'psx_main_reset_fence.sv','psx_vram_stream.sv')],
        source(ROOT/'references/Laxer3a_PSX/hdlGPU/rtl/dual_clock_fifo.sv')]
    unique={s['path']:s for s in sources};sources=list(unique.values())
    for s in sources:
        if s['path']==str(core):s['sha256']=digest(core)
    qsf=directory/'apf_top.qsf';lines=[line for line in qsf.read_text().splitlines()
        if not re.search(r'-name (?:SYSTEMVERILOG_FILE|VERILOG_FILE|VHDL_FILE)',line)]
    lines += [f'set_global_assignment -name {s.get("assignment","VHDL_FILE")} "{s["path"]}" -library {s["library"]}' for s in sources]
    qsf.write_text('\n'.join(lines)+'\n')
    sdc=directory/'pocket.sdc';text=sdc.read_text()
    text=text.replace('ic|memory|memory_clocks|pll|','ic|memory_clocks|pll|')
    text+='''
# New memory single-bit first synchronizer stages only. Numeric payload and
# Gray pointer physical bounds are appended below; payload CDC remains timed.
set_false_path -to [get_registers {*|memory_fault_meta *|sys_reset[0] *|mem_reset[0] *|request_ack_sync[0] *|request_sync[0] *|response_sync[0] *|response_ack_sync[0] *|main_reset_fence|acknowledge_sync[0]}]
'''
    text+='\n'+(ROOT/'scripts/pocket_vram_scope.tcl').read_text()
    sdc.write_text(text)
    manifest['sources']=sources
    for name in manifest['project_hashes']:manifest['project_hashes'][name]=digest(directory/name)
    manifest['kind']='physical-psx-sdram-only-boot'
    manifest['physical_memory_clocks_mhz']={'controller':62.5,'pads':125,'forwarded':125,'forwarded_phase_ps':4000,'PSRAM':None}
    manifest['sdram_only']={'contract':{'path':str(contract),'sha256':digest(contract)},'phy':phy,
        'preparer_sha256':digest(Path(__file__)),'configured_PLL_count':4,'PSRAM_connected':False,
        'PLL_references':{'clk_74a':['CPU','video'],'clk_74b':['memory','audio']},
        'physical_byte_map':{'RAM':0,'VRAM':0x800000,'card1':0x900000,'card2':0xa00000,'SPU':0x1000000,'BIOS':0x1080000},
        'DDR_address_normalization':'Same low26-bit normalization as legacy psx_vram_adapter; +8MiB physical relocation',
        'memory_service_enable':'ce OR savestate_busy; clear handshakes continue while paused',
        'main_reset_fence':{'rtl_sha256':digest(ROOT/'rtl/pocket/psx_main_reset_fence.sv'),
            'preparer_sha256':digest(ROOT/'scripts/prepare_main_reset_fence.py'),
            'ownership':'Fresh 3x drain token after source ownership; CPU/memorymux held in reset',
            'reset_header':'One retained64-bit reply; never advance before old main work drains',
            'consumer_pending':'readram/writeram cleared during held consumer reset',
            'full_candidate_verified':False,'fit_verified':False,'timing_verified':False},
        'vram_gray_constraints':{'helper_sha256':digest(ROOT/'scripts/pocket_vram_scope.tcl'),
            'flight_ns':10,'skew_ns':10,'physical_min_ns':0,'asynchronous_min_exception_ns':-10,
            'false_paths':False,'second_stages_fully_timed':True},
        'full_top_simulation_verified':False,'timing_verified':False,'hardware_verified':False}
    manifest['limitations'].append('New shared SDRAM topology: nominal component traffic proof only; full reset/APF/game/bandwidth/CDC and hardware verification pending')
    manifest['limitations'].append('Main reset fence is new logic; the older1860-LAB fit does not measure this generated configuration')
    (directory/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');return manifest


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--shared-contract',type=Path,required=True)
    parser.add_argument('--template-run',type=Path,default=ROOT/'build/pocket/audio-stream/runs/20261014T075919Z-7d7eaoio')
    parser.add_argument('--output',type=Path,default=ROOT/'build/pocket/sdram-only')
    parser.add_argument('--full-fit',action='store_true')
    parser.add_argument('--map-only',action='store_true')
    args=parser.parse_args()
    if args.full_fit and args.map_only:parser.error('Select one compile scope')
    old=json.loads((args.template_run/'manifest.json').read_text())
    parent=args.output/'runs';parent.mkdir(parents=True,exist_ok=True)
    work=Path(tempfile.mkdtemp(prefix=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ-'),dir=parent)).resolve()
    variants=list(VARIANTS_CURRENT)+['cd-xa-history-clamp','mdec-mednafen']
    manifest=prepare_full(work,variants,True,'area-min-state')
    # Reuse the existing selected candidate contracts, freshly regenerate its
    # sources, and never edit the old fitted project or its bitstream.
    if old.get('cpu_tag_trial'):
        from prepare_cpu_tag_trial import apply_cpu_tag_trial
        manifest=apply_cpu_tag_trial(manifest,work,old['cpu_tag_trial']['contract_report'])
    from prepare_vram_response_enable import apply_response_enable
    manifest=apply_response_enable(manifest,work)
    manifest=apply_audio_stream(manifest,work)
    loader,apf=old['release_boot_loader']['contracts']
    manifest=apply_boot_loader(manifest,work,loader['path'],apf['path'])
    _,proof=validate_cleanup(old['release_host_trim']['contract']['path'],'host')
    manifest=apply_release_host_trim(manifest,work);manifest['release_host_trim']['contract']=proof
    manifest=apply_release_init(manifest,work,old['release_init']['contract']['path'])
    manifest=apply_sdram(manifest,work,args.shared_contract)
    manifest['sdram_only']['selected_variants']=variants
    (work/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');print(work,flush=True)
    if not args.full_fit and not args.map_only:return
    binary=Path(find_tool('quartus_sh')).parent;original_qsf=(work/'apf_top.qsf').read_text()
    (work/'apf_top.qsf.precompile').write_text(original_qsf)
    report={'steps':[],'timing_verified':False,'hardware_verified':False,'target_LABs':1663}
    with (work/'quartus.log').open('w') as log:
        for name in (('quartus_map',) if args.map_only else ('quartus_map','quartus_fit','quartus_sta','quartus_asm')):
            result=subprocess.run([str(binary/name),'apf_top'],cwd=work,stdout=log,stderr=subprocess.STDOUT,timeout=3600)
            report['steps'].append({'tool':name,'exit_code':result.returncode})
            print(name,result.returncode,flush=True)
            if result.returncode:break
    report['source_identity_verified']=all(digest(Path(s['path']))==s['sha256'] for s in manifest['sources'])
    report['functional_project_identity_verified']=all(digest(work/name)==sha for name,sha in manifest['project_hashes'].items() if name!='apf_top.qsf') and (
        digest(work/'apf_top.qsf')==manifest['project_hashes']['apf_top.qsf'] or compiler_version_append_only(original_qsf,(work/'apf_top.qsf').read_text()))
    report['compiled_project_hashes']={n:digest(work/n) for n in manifest['project_hashes']}
    (work/'compile-report.json').write_text(json.dumps(report,indent=2)+'\n');print(work/'compile-report.json',flush=True)
    if report['steps'][-1]['exit_code'] or not report['source_identity_verified'] or not report['functional_project_identity_verified']:
        raise SystemExit(1)


if __name__=='__main__':main()
